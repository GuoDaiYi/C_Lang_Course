/*
 * ============================================================================
 *  小项目 1：猜数字游戏
 * ============================================================================
 *
 *  ▶ 这个项目是什么
 *  ---------------------------------------------------------------------------
 *    一个能真正玩起来的小游戏：电脑随机想一个 1~100 的数字，你有 7 次机会猜。
 *    每猜一次，程序会告诉你「大了」「小了」，还会额外提示你差多少
 *    （就差一点点 / 很接近了 / 还差得挺远 / 差得很远）。
 *
 *    它看着简单，但把前面学的几乎所有东西都用上了：
 *    循环、判断、函数、数组之外的字符串、指针、随机数、输入校验。
 *    **看懂这个程序，就说明你真的入门了。**
 *
 *  ▶ 做这个项目之前，你需要已经会（前置知识）
 *  ---------------------------------------------------------------------------
 *    ✅ 第 3 课：会用 scanf 读用户输入，并且会检查 scanf 的返回值
 *    ✅ 第 4 课：会用 if / else 做多分支判断
 *    ✅ 第 5 课：会用 switch 做菜单式选择
 *    ✅ 第 6 课：会用 for 和 while 循环，特别是 while (1) 这种「一直转」的写法
 *    ✅ 第 7 课：会定义函数、传参数、返回值；知道 C 的参数是「值传递」
 *    ✅ 第 9 课：会用 char 数组存字符串
 *    ✅ 第 10 课：会用指针（这个项目里用指针把数字「带」回函数外面）
 *    🔁 忘了就看：第 6 课的 while 循环、第 7 课的函数、第 10 课的指针
 *    ❓ 开课自测（能答上来再往下看，答案在文件最末尾）
 *       1) 怎么让程序每次运行时猜的数都不一样？
 *       2) scanf 读到用户输入的字母时，返回值是多少？
 *       3) 为什么 read_number 这个函数要写成 int read_number(..., int *out)，
 *          而不能直接 return 读到的那个数？
 *
 *  ▶ 本项目新出现的语法
 *  ---------------------------------------------------------------------------
 *    1) #define MAX_NUMBER  100
 *       读作：定义一个叫 MAX_NUMBER 的宏，值是 100
 *       作用：给「魔法数字」起个名字。写 100 处的地方一律写 MAX_NUMBER，
 *             想改成 1~1000 只要改这一行。
 *       注意：宏没有类型，编译器会把它直接替换成字面量 100。
 *
 *    2) rand() 和 srand(种子)
 *       读作：随机数 / 设置随机种子
 *       作用：rand() 返回一个伪随机整数；srand() 决定随机序列从哪开始。
 *       注意：不调 srand 的话，rand() 每次运行都返回一模一样的序列——
 *             所以必须用当前时间来当种子。
 *
 *    3) time(NULL)
 *       读作：取当前时间
 *       作用：返回从 1970 年 1 月 1 日到现在的秒数，拿它当随机种子。
 *
 *    4) const char *prompt 和 int *out
 *       读作：指向常量字符的指针 / 指向整数的指针
 *       作用：read_number 需要「告诉别人提示语是什么」和「把读到的数放哪」。
 *             字符串用指针传（数组名会自动变成首地址），数字用指针传
 *             （因为 C 的参数是值传递，不传地址的话函数改不动外面的变量）。
 *       注意：写 const char * 表示「我只看看，不改它」。
 *
 *    5) snprintf(缓冲区, 缓冲区大小, 格式, ...)
 *       读作：安全的格式化写入
 *       作用：把格式化后的文字写进数组，并且保证不会写超（比 sprintf 安全）。
 *       注意：第二个参数必须写 sizeof(缓冲区)，不能写数组的长度数字。
 *
 *    6) getchar() 和 EOF
 *       读作：读一个字符 / 文件结束标志
 *       作用：getchar() 一次读一个字符；EOF 表示「已经没东西可读了」
 *             （用户按了 Ctrl+D，或输入被重定向用完了）。
 *
 *    7) scanf 返回值的三种情况
 *       1  = 成功读到 1 个整数
 *       0  = 读到了但格式不对（比如用户输入了字母）
 *      EOF = 什么都没读到，输入已经结束
 *       作用：靠它区分「用户输错了」和「用户不玩了」，这很重要——
 *             分不清的话程序会一直提示「请重新输入」，变成死循环。
 *
 *  ▶ 程序结构地图（先看懂这张地图，再看代码会轻松很多）
 *  ---------------------------------------------------------------------------
 *    整个程序由 4 个部分组成，从下往上调用：
 *
 *      main()                    ← 总指挥：循环玩多局、统计战绩、问要不要再来一局
 *        └─ play_one_round()     ← 玩一局：生成答案、循环猜 7 次、返回用了几次
 *             └─ read_number()   ← 读一次输入：成功返回 0，输错返回 -1，输入结束返回 -2
 *                  └─ clear_input()  ← 把输入缓冲区里剩余的字符（换行等）清掉
 *
 *    数据怎么流动：
 *      用户键盘 → scanf → read_number 通过 &out 把数字写进 guess
 *                → play_one_round 拿去和 answer 比较
 *                → 返回结果 → main 拿去更新战绩
 *
 *  ▶ 怎么读这个文件
 *  ---------------------------------------------------------------------------
 *    1. 先读上面这几块，重点是「程序结构地图」；
 *    2. 建议阅读顺序：main → play_one_round → read_number → clear_input，
 *       也就是从上往下顺着调用链读；
 *    3. 代码里每个函数前面都有「▶▶▶ 第 N 段」导读，讲清这个函数干什么；
 *    4. 一定要自己跑一遍，用 y/n 那一问体验一下输入校验的分支；
 *    5. 最后做「动手练习」。
 *
 *  运行方式（在本项目根目录下）：
 *    make run L=projects/guess_number
 *    或者手动：cc projects/guess_number.c -o guess && ./guess
 * ============================================================================
 */

#include <stdio.h>
#include <stdlib.h>   /* rand、srand */
#include <time.h>     /* time，用来给随机数做种子 */

/* ▶▶▶ 第 1 段：用宏给魔法数字起名字
 *  做什么：把「最大数字」和「最多猜几次」抽成两个常量。
 *  新语法：#define
 *  预期输出：本身不产生输出，只是让后面的代码更好读、更好改。
 */
#define MAX_NUMBER  100
#define MAX_TRIES   7

/* ▶▶▶ 第 2 段：clear_input —— 把输入缓冲区里剩下的字符全部读掉
 *  做什么：scanf 读数字时会把后面的换行符留在缓冲区里。
 *         下一次 scanf 读字符串时，那个换行符会被读成一个「空字符串」，
 *         导致程序莫名其妙。所以要把这一行剩下的东西清干净。
 *  新语法：getchar()、EOF
 *  预期输出：不产生输出，只做「清理」这件事。
 */
void clear_input(void) {
    int c;
    while ((c = getchar()) != '\n' && c != EOF) {
        /* 空循环：一直读到行尾或文件结束，什么也不做 */
    }
}

/* ▶▶▶ 第 3 段：read_number —— 读一个整数，并区分三种情况
 *  做什么：打印提示语，读取用户输入，用返回值告诉调用者结果如何。
 *
 *         返回  0 -> 读成功，数字已经写进 *out
 *         返回 -1 -> 输入的不是整数（可以重新输入）
 *         返回 -2 -> 输入已经结束，比如按了 Ctrl+D 或输入重定向用完了
 *
 *         区分 -1 和 -2 很重要：如果不处理「输入结束」，
 *         程序就会一直提示「请重新输入」而永远等不到数据 —— 死循环。
 *
 *  新语法：指针参数 out、scanf 返回值、EOF
 *  预期输出：先打印 prompt 里的话，然后等用户输入。
 */
int read_number(const char *prompt, int *out) {
    printf("%s", prompt);
    int rc = scanf("%d", out);

    if (rc == EOF) {
        printf("\n");
        return -2;          /* 输入结束了 */
    }
    if (rc != 1) {
        clear_input();      /* 输入了字母之类，把这一行残余清掉 */
        return -1;          /* 格式不对，可以重来 */
    }
    return 0;               /* 一切正常 */
}

/* ▶▶▶ 第 4 段：play_one_round —— 完整地玩一局
 *  做什么：生成一个 1~100 的随机答案，给玩家最多 7 次机会去猜，
 *         根据猜测结果给出「大了/小了 + 差多少」的提示。
 *         猜中时返回用了几次；没猜中返回 -1。
 *  新语法：rand()、for 循环、continue、break
 *  预期输出（长这样，具体数字每次都不同）：
 *      我想好了一个 1 到 100 之间的数字，你有 7 次机会。
 *      第 1 次机会，请输入你的猜测：50
 *        大了，还差得挺远。
 *      ...
 */
int play_one_round(void) {
    /* rand() 产生伪随机数。不用 srand 设置种子的话，
     * 每次运行得到的结果都一样，所以要用当前时间当种子。 */
    int answer = rand() % MAX_NUMBER + 1;   /* % 100 得到 0~99，+1 变成 1~100 */
    int guess = 0;

    printf("\n我想好了一个 1 到 %d 之间的数字，你有 %d 次机会。\n",
           MAX_NUMBER, MAX_TRIES);

    for (int tries = 1; tries <= MAX_TRIES; tries++) {
        char prompt[64];
        /* snprintf 把「第几次机会」拼成一句提示语，写进 prompt 数组 */
        snprintf(prompt, sizeof(prompt), "第 %d 次机会，请输入你的猜测：", tries);

        int rc = read_number(prompt, &guess);

        if (rc == -2) {
            printf("输入结束了，这一局先玩到这儿。\n");
            return -1;
        }

        if (rc == -1) {
            printf("  这不是一个数字，这次不算，请重新输入。\n");
            tries--;            /* 输入错误不消耗机会 */
            continue;           /* 回到 for 开头，注意 tries 已经减回去了 */
        }

        if (guess < 1 || guess > MAX_NUMBER) {
            printf("  超出范围了，请输入 1 到 %d 之间的数。\n", MAX_NUMBER);
            tries--;            /* 同上，也不消耗机会 */
            continue;
        }

        if (guess == answer) {
            printf("\n恭喜！答案就是 %d，你用了 %d 次猜中。\n", answer, tries);
            if (tries == 1) {
                printf("一次就中，运气太好了！\n");
            } else if (tries <= 3) {
                printf("很厉害！\n");
            }
            return tries;        /* 返回用了几次 */
        }

        /* 没猜中，给点提示 */
        int diff = guess - answer;      /* 正数说明猜大了，负数说明猜小了 */
        if (diff > 0) {
            printf("  大了");
        } else {
            printf("  小了");
        }

        diff = (diff < 0) ? -diff : diff;   /* 三目运算符：取绝对值 */

        if (diff <= 3) {
            printf("，就差一点点！\n");
        } else if (diff <= 10) {
            printf("，很接近了。\n");
        } else if (diff <= 30) {
            printf("，还差得挺远。\n");
        } else {
            printf("，差得很远哦。\n");
        }
    }

    printf("\n次数用完了。正确答案是 %d。\n", answer);
    return -1;
}

/* ▶▶▶ 第 5 段：main —— 总指挥
 *  做什么：把随机种子设好，然后循环玩多局，一边玩一边统计战绩，
 *         每局结束问玩家要不要再来一局。
 *  新语法：while (1)、srand、time(NULL)
 *  预期输出（开头长这样）：
 *      ========================================
 *                  猜 数 字 游 戏
 *      ========================================
 *      ========== 第 1 局 ==========
 *      ...
 */
int main(void) {
    /* 用当前时间当随机种子。启动时调用一次就够，不要写在循环里。 */
    srand((unsigned)time(NULL));

    printf("========================================\n");
    printf("            猜 数 字 游 戏\n");
    printf("========================================\n");

    int round_no = 0;        /* 玩了第几局 */
    int wins = 0;            /* 赢了几局 */

    while (1) {              /* 1 永远为真，所以这个循环不会自己结束 */
        round_no++;
        printf("\n========== 第 %d 局 ==========\n", round_no);

        if (play_one_round() > 0) {   /* 返回值 > 0 表示赢了 */
            wins++;
        }

        printf("\n当前战绩：玩了 %d 局，赢了 %d 局。\n", round_no, wins);

        printf("再来一局？(y/n)：");
        char c = 0;
        if (scanf(" %c", &c) != 1) {   /* 前面的空格表示跳过空白和换行 */
            break;                    /* 读不到就退出循环 */
        }
        clear_input();

        if (c != 'y' && c != 'Y') {
            break;                    /* 玩家不想玩了，退出 */
        }
    }

    printf("\n感谢游玩，再见！\n");
    return 0;
}

