/*
 * ============================================================================
 *  第 12 课：文件读写（让数据活得更久）
 * ============================================================================
 *
 *  本课知识点：FILE*、fopen 的模式、检查 NULL、fprintf 写、
 *              fgets 读、fscanf 读、fclose、追加模式
 *
 *  ▶ 这节课要解决什么问题
 *  ---------------------------------------------------------------------------
 *    到目前为止，你写的所有程序都有一个共同的毛病：
 *
 *      程序一结束，变量里的数据就跟着消失了。
 *      你让用户输入了 5 个成绩，程序算完平均分，屏幕一关——什么都没剩下。
 *
 *    这就像你在草稿纸上算账，算完把纸一扔。下次想看，得从头再算一遍。
 *
 *    文件就是那张「能保存的纸」。学会这一课，你能：
 *      1) 把数据写到硬盘上的文件里，程序关了它还在；
 *      2) 下次运行程序时再把数据读回来接着用；
 *      3) 用「追加」模式往老数据后面接着记，像记流水账一样不会覆盖；
 *      4) 知道怎么判断文件打不开，避免一打开就崩溃。
 *
 *    这套本事是「成绩管理系统」「记账本」「日志程序」的共同地基。
 *
 *  ▶ 学这节课之前，你需要已经会（前置知识）
 *  ---------------------------------------------------------------------------
 *    ✅ 已经会：第 3 课：让程序会问问题（会用 scanf 读键盘输入）
 *    ✅ 已经会：第 6 课：循环（会用 while、for，知道循环里可以累加计数）
 *    ✅ 已经会：第 8 课：数组（会用 char 数组存字符串，知道下标从 0 开始）
 *    ✅ 已经会：第 9 课：字符串（会用 %s 打印字符串、知道字符串末尾有 '\0'）
 *    ✅ 已经会：第 10 课：指针（知道 FILE * 是一个指针，知道 NULL 表示「空的」）
 *    🔁 忘了就看：第 3 课「scanf 读整数要写 &，读字符串不用」
 *    🔁 忘了就看：第 10 课「用指针之前先判断它是不是 NULL」
 *    🔁 忘了就看：第 9 课「strlen 是几个字符，sizeof 是占多少字节」
 *    ❓ 开课自测（4 题，能答上来再往下学；答案在文件最末尾）
 *       1) 程序里的变量值，关掉程序以后还在吗？为什么？
 *       2) fopen 打开了文件却没检查返回值，可能会出什么事？
 *       3) fgets 要写几个参数？分别是什么意思？
 *       4) "w" 和 "a" 两个打开模式，最关键的区别是什么？
 *
 *  ▶ 本节课新出现的语法（先扫一眼这张表，看不懂的先跳过，学到自然会懂）
 *  ---------------------------------------------------------------------------
 *    1) FILE *
 *       读作：文件指针
 *       作用：C 标准库把「一个已经打开的文件」包装成 FILE 类型，
 *             用 FILE * 这个指针来指向它。后面的 fopen 返回的就是它。
 *       注意：FILE 是库自己定义的类型，你不用（也不能）自己写它的成员，
 *             只当它是个「文件句柄」用就行。
 *
 *    2) fopen(文件名, 模式)
 *       读作：打开文件
 *       作用：打开（或创建）一个文件，返回一个 FILE * 指针。
 *       注意：第一个参数是文件名的字符串，第二个参数是模式的字符串，
 *             两个都必须加双引号。
 *
 *    3) 打开模式 "r" / "w" / "a" / "r+"
 *       读作：只读 / 覆盖写 / 追加 / 读写
 *       作用：决定这个文件「能干什么」：
 *             "r"  只读。文件必须已经存在，否则失败。
 *             "w"  只写。文件不存在就创建；已经存在就把里面的内容【全部清空】重写。
 *             "a"  追加。只写，但内容接到文件末尾，老数据不会被清掉。
 *             "r+" 读写。文件必须存在。
 *       注意：★ "w" 很危险 —— 它会先清空整个文件。
 *             想保留旧数据一定用 "a"。
 *
 *    4) fp == NULL
 *       读作：fp 是空的
 *       作用：检查 fopen 有没有失败。失败时它返回 NULL。
 *             失败的原因通常是：路径不存在、目录没权限、文件被占用。
 *       注意：这一步绝对不能省！忘了判断，后面一操作就崩溃。
 *
 *    5) fprintf(fp, "...", ...)
 *       读作：格式化打印到文件
 *       作用：和 printf 用法一模一样，只是最前面多了一个「往哪儿写」。
 *       注意：printf 写的是屏幕，fprintf 写的是文件。别的完全一样。
 *
 *    6) fgets(缓冲区, 缓冲区大小, 文件指针)
 *       读作：从文件里读一行，放进缓冲区
 *       作用：三个参数，缺一不可：
 *             ① 缓冲区（char 数组）：读进来的文字放这儿；
 *             ② 缓冲区大小：最多读几个字符（实际最多读 size-1 个，
 *                最后一个位置要留给结尾的 '\0'）；
 *             ③ 文件指针：从哪个文件读。
 *             一次读一行，读到文件末尾就返回 NULL。
 *       注意：所以判断文件读没读完的标准写法是
 *             while (fgets(line, sizeof(line), fp) != NULL) { ... }
 *
 *    7) fscanf(fp, "...", ...)
 *       读作：格式化扫描（从文件）
 *       作用：和 scanf 用法相同，只是数据来源从键盘换成了文件。
 *       注意：返回值是「成功读到的字段个数」。读到文件末尾会返回 EOF，
 *             所以判断一行有没有读全，用 == 3（你写了几个字段就比几）。
 *
 *    8) fclose(fp)
 *       读作：关闭文件
 *       作用：把文件收尾关好。
 *       注意：用完必须关！不关的话数据可能还留在缓冲区里没真正写进磁盘，
 *             而且系统能同时打开的文件个数有限。
 *
 *    9) EOF
 *       读作：文件结束标志（End Of File）
 *       作用：一个特殊常量，表示「已经读到文件末尾，没有更多内容了」。
 *       注意：它是 int 类型的负数，通常写成 -1。
 *             fgets 读到末尾返回 NULL，fscanf 读到末尾返回 EOF——
 *             两个函数表达「结束」的方式不一样，别搞混。
 *
 *    10) const char *filename = "students.txt";
 *       读作：常量字符串指针 filename，指向 "students.txt"
 *       作用：把文件名存起来，之后反复使用，也方便改。
 *       注意：这是第 9 课的字符串 + 第 10 课的指针。
 *             字符串常量在 C 里本来就是「用指针指向一串字」的写法。
 *
 *    11) const int LINE_SIZE = 200;  /  const int NAME_SIZE = 50;
 *       读作：常量 LINE_SIZE 等于 200
 *       作用：给「缓冲区有多大」起个名字，改的时候只改一处。
 *       注意：缓冲区长度减 1 才是能安全读入的字符数——
 *             剩下的那个位置要留给结尾的 '\0'。
 *             所以 %49s 里的 49 正好是 NAME_SIZE - 1。
 *
 *  ▶ 怎么读这个文件
 *  ---------------------------------------------------------------------------
 *    1. 先读完上面这三块（问题 / 前置 / 新语法），心里先有个框架；
 *    2. 往下看代码，每段代码前面都有「▶▶▶ 第 N 段」，讲清这段在干嘛、
 *       跑起来会看到什么；
 *    3. 边看边在脑子里预演输出，觉得「我大概知道这段会打印什么」再往下走；
 *    4. 最后做「动手练习」和「自测题」。
 *
 *  运行方式（在本项目根目录下）：
 *    make run L=lessons/12_files
 *    或者手动：cc lessons/12_files.c -o demo && ./demo
 *
 *  ★ 注意：程序会在「当前目录」创建和读取 students.txt 和 report.txt。
 *    运行完可以在运行程序的目录下用文本编辑器打开看看。
 * ============================================================================ */

#include <stdio.h>

int main(void) {
    const char *filename = "students.txt";
    const int LINE_SIZE = 200;     /* 一行最多读多少个字符 */
    const int NAME_SIZE = 50;      /* 姓名缓冲区有多大 */

    /* ▶▶▶ 第 1 段：写文件 —— 用 "w" 模式打开
     *  做什么：用 "w" 模式打开 students.txt，然后往里写 3 条学生记录。
     *  新语法：FILE *、fopen(filename, "w")、检查 fp == NULL、fprintf(fp, ...)
     *  预期输出：
     *      已写入 3 条记录到 students.txt
     *    （文件本身不会出现任何内容，因为它在磁盘上，不在屏幕上）
     */
    /* ============================================================
     * 一、写文件
     * ------------------------------------------------------------
     * fopen(文件名, 模式)：
     *   "r"  只读，文件必须存在
     *   "w"  只写，文件不存在就创建，存在则【清空重写】
     *   "a"  追加，写到文件末尾，不会清空原来的内容
     *   "r+" 读写
     * 返回 FILE*，失败时返回 NULL（比如路径不存在、没有权限）。
     * ============================================================ */

    FILE *fp = fopen(filename, "w");
    if (fp == NULL) {
        /* 这一步绝对不能省！忘了判断，后面一操作就崩溃。 */
        printf("打不开文件 %s\n", filename);
        return 1;
    }

    /* fprintf 和 printf 用法一模一样，只是多了一个「往哪儿写」 */
    fprintf(fp, "%s %d %d\n", "小明", 1001, 88);
    fprintf(fp, "%s %d %d\n", "小红", 1002, 95);
    fprintf(fp, "%s %d %d\n", "小刚", 1003, 72);

    printf("已写入 3 条记录到 %s\n", filename);

    fclose(fp);
    /* 用完必须关！不关的话，数据可能还留在缓冲区里没真正写进磁盘。
     * 记住口诀：fopen 之后，一定要有 fclose。 */

    /* ▶▶▶ 第 2 段：追加模式 —— 在原有内容后面继续写
     *  做什么：再用 "a" 模式打开同一个文件，多写一条「小美」的记录。
     *          注意这次没有再写 printf 提示语，是故意的——保持输出干净。
     *  新语法：fp = fopen(filename, "a")（复用同一个指针变量，这是常见写法）
     *  预期输出：
     *      已追加 1 条记录（现在共 4 条）
     *    跑完以后打开 students.txt，会看到 4 行：
     *      小明 1001 88 / 小红 1002 95 / 小刚 1003 72 / 小美 1004 60
     */
    /* ============================================================
     * 二、追加模式：在原有内容后面继续写
     * ============================================================ */

    fp = fopen(filename, "a");       /* 复用同一个指针变量，这也是常见写法 */
    if (fp == NULL) {
        printf("打不开文件\n");
        return 1;
    }
    fprintf(fp, "%s %d %d\n", "小美", 1004, 60);
    fclose(fp);
    printf("已追加 1 条记录（现在共 4 条）\n");

    /* ▶▶▶ 第 3 段：读文件（方式一）—— 整行读取，最常用也最安全
     *  做什么：用 "r" 模式打开文件，用 fgets 一行一行读，
     *          读到的每一行前面加上行号打印出来，最后统计总行数。
     *  新语法：char line[LINE_SIZE]、fgets(line, sizeof(line), fp)、
     *          while (fgets(...) != NULL)
     *  预期输出：
     *      （空行）
     *      --- 读取并打印文件内容 ---
     *       1| 小明 1001 88
     *       2| 小红 1002 95
     *       3| 小刚 1003 72
     *       4| 小美 1004 60
     *      共 4 行
     */
    /* ============================================================
     * 三、读文件 —— 方式 1：整行读取，最常用也最安全
     * ============================================================ */

    printf("\n--- 读取并打印文件内容 ---\n");
    fp = fopen(filename, "r");
    if (fp == NULL) {
        printf("文件不存在\n");
        return 1;
    }

    char line[LINE_SIZE];
    int line_number = 0;

    /* fgets 每次读一行（最多 size-1 个字符），读到文件末尾返回 NULL。
     * 所以「while (fgets(...) != NULL)」就是遍历整个文件的标准写法。 */
    while (fgets(line, sizeof(line), fp) != NULL) {
        line_number++;
        printf("%2d| %s", line_number, line);   /* line 里已经含换行符了 */
    }
    fclose(fp);
    printf("共 %d 行\n", line_number);

    /* ▶▶▶ 第 4 段：读文件（方式二）—— 按格式解析每一行的数据
     *  做什么：再打开一次文件，这次用 fscanf 按「姓名 学号 成绩」的格式
     *          把每行拆成三个数据，打印每个人的成绩，并统计总分和人数。
     *  新语法：fscanf(fp, "%49s %d %d", name, &id, &score) == 3
     *  预期输出：
     *      （空行）
     *      --- 解析数据并统计 ---
     *      小明 的成绩是 88
     *      小红 的成绩是 95
     *      小刚 的成绩是 72
     *      小美 的成绩是 60
     *      共 4 人，总分 315，平均 78.75
     */
    /* ============================================================
     * 四、读文件 —— 方式 2：按格式解析每一行的数据
     * ============================================================ */

    printf("\n--- 解析数据并统计 ---\n");
    fp = fopen(filename, "r");
    if (fp == NULL) {
        printf("文件不存在\n");
        return 1;
    }

    char name[NAME_SIZE];
    int id = 0;
    int score = 0;
    int sum = 0;
    int count = 0;

    /* fscanf 和 scanf 用法相同，只是从文件里读。
     * 返回值是成功读到的项数；读到文件末尾返回 EOF（-1），
     * 所以用「== 3」判断是否成功读满了 3 个字段。
     * 注意 %49s 里的 49 = NAME_SIZE - 1，留一个位置给结尾的 '\0'。 */
    while (fscanf(fp, "%49s %d %d", name, &id, &score) == 3) {
        printf("%s 的成绩是 %d\n", name, score);
        sum += score;
        count++;
    }
    fclose(fp);

    if (count > 0) {
        printf("共 %d 人，总分 %d，平均 %.2f\n", count, sum, (double)sum / count);
    }

    /* ▶▶▶ 第 5 段：更多实用写法
     *  做什么：三件小事——
     *          ① 把统计结果写进另一个文件 report.txt；
     *          ② 试着打开一个根本不存在的文件，观察 fopen 返回 NULL；
     *          ③ 提醒自己「用 "w" 打开已有文件会清空它」。
     *  新语法：fopen("report.txt", "w")、if (report != NULL)
     *  预期输出：
     *      （空行）
     *      已生成 report.txt
     *      文件不存在时 fopen 会返回 NULL，这就是判断方法
     */
    /* ============================================================
     * 五、更多实用写法
     * ============================================================ */

    /* 1) 把数据「一次性」写进文件，方便下次直接读回来 */
    if (count > 0) {                  /* 有人数才写报告，
                                       * 否则 (double)sum / count 会除以 0 */
        FILE *report = fopen("report.txt", "w");
        if (report != NULL) {
            fprintf(report, "===== 成绩报告 =====\n");
            fprintf(report, "人数: %d\n", count);
            fprintf(report, "总分: %d\n", sum);
            fprintf(report, "平均分: %.2f\n", (double)sum / count);
            fclose(report);
            printf("\n已生成 report.txt\n");
        }
    }

    /* 2) 检查文件是否存在（试着打开一下就知道） */
    FILE *test = fopen("不存在的文件.txt", "r");
    if (test == NULL) {
        printf("文件不存在时 fopen 会返回 NULL，这就是判断方法\n");
    } else {
        fclose(test);
    }

    /* 3) 想重新覆盖写入，只要用 "w" 打开，旧内容就自动被清掉了 */

    return 0;
}

