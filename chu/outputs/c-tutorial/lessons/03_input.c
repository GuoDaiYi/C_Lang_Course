/*
 * ============================================================================
 *  第 3 课：让程序会问问题（读取用户输入）
 * ============================================================================
 *
 *  ▶ 这节课要解决什么问题
 *  ---------------------------------------------------------------------------
 *    前两课的程序，所有数据都是我们自己在代码里写死的：
 *    int age = 18; 用户改成 19 还得好意思回来改代码。
 *
 *    这一课要让程序学会「开口问」。
 *    打个比方：以前程序像一份印好的问卷，用户只能看；
 *    现在程序像银行窗口，会问「请输入您的金额」，你敲进去，它才能接着办。
 *
 *    学完这节课，你能：
 *      · 让程序等待用户敲键盘，用 scanf 把输入读进变量；
 *      · 知道那个总被漏掉的 & 到底是什么意思（它是新手第一号 bug）；
 *      · 会检查用户有没有乱输（scanf 的返回值）；
 *      · 会读一整行文字（包括带空格的名字）。
 *
 *  ▶ 学这节课之前，你需要已经会（前置知识）
 *  ---------------------------------------------------------------------------
 *    ✅ 已经会：第 1 课：第一个 C 程序
 *       （会写 main、每条语句加分号、会用 printf 打印）
 *    ✅ 已经会：第 2 课：变量与数据类型
 *       （会声明 int / double / char 变量、知道格式符要和类型对上、
 *         知道整数除法会丢小数）
 *    🔁 忘了就看：第 2 课「第 3 段」的 %d / %f / %c，
 *       和第 2 课「第 5 段」的整数除法陷阱；
 *       第 1 课文件末尾「本课小结」里的 printf 用法。
 *    ❓ 开课自测（这 4 题能答上来再往下学，答案在文件最末尾）
 *       1) int 和 double 最大的区别是什么？哪个能装下 1.75？
 *       2) printf("%d 岁\n", 18); 里的 %d 和逗号后面的 18 分别是什么意思？
 *       3) 7 / 2 的结果是多少？想让结果是 3.5，该怎么写？
 *       4) 一个 int 变量能装下 200 吗？那 char 呢？
 *
 *  ▶ 本节课新出现的语法（先扫一遍这张表，看不懂的先跳过，学到自然会懂）
 *  ---------------------------------------------------------------------------
 *    1) #include <string.h>
 *       读作：包含 头文件 string.h
 *       作用：把「字符串工具箱」请进来。后面要用的 strlen、strcspn 住在里面。
 *       注意：这行要写在 #include <stdio.h> 的下面，别忘了。
 *
 *    2) scanf("%d", &age);
 *       读作：扫描输入 格式"整数" 放到 age 的地址里
 *       作用：从键盘读一个整数，存进 age 变量。
 *       注意：程序会「停在那里等」你敲键盘，你敲完必须按回车；
 *             没有回车，程序就一直等，屏幕上还看不见你在想什么。
 *
 *    3) & —— 取地址符（本课头号知识点）
 *       写法：scanf("%d", &age);
 *       读作：&age 就是「age 这个变量在内存里的地址」
 *       作用：scanf 必须知道「把读到的数字放到哪儿」，所以要的是地址，不是值。
 *       注意：printf 不需要 &（它只是把值读出来用），scanf 需要（它要往里写）。
 *             漏掉 & 轻则读出一堆垃圾数，重则直接段错误崩溃。
 *
 *    4) %lf（scanf 读 double 用）
 *       写法：scanf("%lf %lf", &width, &height);
 *       读作：长 double 双精度浮点 ×2
 *       作用：一次读两个小数。
 *       注意：scanf 读 double 用 %lf（多一个字母 l），
 *             但 printf 打印 double 还是 %f。这俩千万别记混——
 *             记混了会读到乱码一样的数。
 *
 *    5) scanf 的返回值
 *       写法：read_count = scanf("%d", &number);
 *       读作：scanf 返回「成功读到了几个数据」
 *       作用：判断用户有没有乱输。读到 1 个才算成功，0 个说明没读成。
 *       注意：scanf 读失败时不会报错，它只是「什么都没读到」，
 *             所以必须自己检查返回值。
 *             （想写成 if (read_count != 1) { ... } 是可以的，
 *               但 if 是第 4 课的内容，这节课我们先把返回值打印出来看个明白。）
 *
 *    6) char word[50] = {0};
 *       读作：字符数组 word，长度 50，全部初始化为 0
 *       作用：准备一个能装 50 个字符的「小柜子」。
 *       注意：数组第 8 课会细讲，这里先照着用；
 *             {0} 的意思是「先把整个柜子清空」，是好习惯。
 *
 *    7) %s（scanf 读字符串）
 *       写法：scanf("%s", word);
 *       读作：读一串字符，放进 word
 *       作用：读一段不带空格的文字。
 *       注意：这里【没有】 & —— 因为数组名本身就代表地址，加了反而会编译报错。
 *             而且 %s 遇到空格就停，读不了带空格的名字。
 *
 *    8) strlen(字符串)
 *       读作：字符串长度
 *       作用：数一数字符串有几个字符。
 *       注意：它的返回值类型是 size_t，所以配套格式符是 %zu，不是 %d。
 *
 *    9) fgets(缓冲区, 缓冲区大小, stdin)
 *       写法：fgets(full_name, sizeof(full_name), stdin);
 *       读作：读一行 到 full_name，最多 sizeof(full_name) 个字节，从标准输入读
 *       作用：读一整行（带空格也行）。
 *       注意：它会把行末的换行符也一起读进来，通常要手动去掉。
 *
 *    10) strcspn(字符串, "\n")  和  '\0'
 *        读作：字符串 A 里第一个出现在 B 里的字符的位置；单引号零 = 空字符
 *        作用：找到换行符在第几个位置，再把那个位置换成 '\0'，
 *              字符串就在这里「结束」，换行符被吃掉了。
 *        注意：'\0' 是一个特殊字符，表示「字符串到此为止」，不是字符 '0'。
 *
 *    11) stdin
 *        读作：标准输入
 *        作用：就是「键盘」这条输入通道。fgets 要指定从哪儿读，就写它。
 *
 *    12) 变量的初始值
 *        写法：int number = 0;
 *        读作：整型 变量 number 等于 0
 *        作用：声明时先给个兜底值，万一后面没读到东西，变量里也不是随机垃圾。
 *        注意：scanf 读失败时不会动这个变量，所以 0 会被保留下来——
 *              这就是「先给初值」的价值。
 *
 *  ▶ 怎么读这个文件
 *  ---------------------------------------------------------------------------
 *    1. 先读完上面三块（问题 / 前置 / 新语法），心里有框架；
 *    2. 往下看代码，每段前面有「▶▶▶ 第 N 段」，讲清这段在干嘛、跑起来看到什么；
 *    3. 边看边预演输出——注意这个程序要你先输入，它才会往下走；
 *    4. 最后做「动手练习」和「自测题」。
 *
 *  运行方式（在本项目根目录下）：
 *    make run L=lessons/03_input
 *    或者手动：cc lessons/03_input.c -o demo && ./demo
 *    这个程序需要你手动输入，运行后按提示敲数字再回车。
 * ============================================================================
 */

#include <stdio.h>
#include <string.h>   /* 下面用到了 strlen，所以要包含它 */

int main(void) {

    /* ▶▶▶ 第 1 段：读一个整数
     *  做什么：程序先打印一句提示，然后停下来等你敲键盘；
     *         你敲的数字被 scanf 读进 age 变量。
     *         age 声明时就给了 0，这是好习惯：声明时先给个初始值，
     *         避免出现随机垃圾值。
     *  新语法：scanf("%d", &age) 和取地址符 &
     *  预期输出（输入 18）：
     *     请输入你的年龄，然后按回车：你今年 18 岁，明年 19 岁。
     *     （后面还有一个空行，因为格式串结尾写了两个换行）
     */
    int age = 0;   /* 好习惯：声明时先给个初始值，避免出现随机垃圾值 */
    printf("请输入你的年龄，然后按回车：");

    scanf("%d", &age);
    /* 两个要点：
     * 1) %d 说明要读一个整数，和 printf 的写法一致；
     * 2) &age 里的 & 表示「这个变量在内存里的地址」——
     *    scanf 需要知道把读到的数字放到哪里，所以要给它地址。
     *    忘了写 & 是最常见的错误之一，程序可能直接崩溃。 */

    printf("你今年 %d 岁，明年 %d 岁。\n\n", age, age + 1);

    /* ▶▶▶ 第 2 段：一次读两个数 / 读小数
     *  做什么：读长方形的宽和高，算出面积。
     *         格式串 "%lf %lf" 中间那个空格有讲究：它让 scanf 跳过任意多个
     *         空格和换行，所以你输入「3.5 2」和「3.5  空格  2」都行。
     *  新语法：%lf（scanf 读 double）、一次给多个变量传地址
     *  预期输出（输入 3.5 2）：
     *     请输入长方形的宽和高（用空格隔开，例如 3.5 2）：宽 3.50，高 2.00，面积 = 7.00
     */
    double width = 0.0;
    double height = 0.0;
    printf("请输入长方形的宽和高（用空格隔开，例如 3.5 2）：");
    scanf("%lf %lf", &width, &height);
    /* double 用 scanf 读是 %lf（多一个 l！），printf 打印仍是 %f。
     * float 用 scanf 读是 %f。这个细节特别容易搞混。 */

    printf("宽 %.2f，高 %.2f，面积 = %.2f\n\n", width, height, width * height);

    /* ▶▶▶ 第 3 段：用 scanf 的返回值做输入校验
     *  做什么：scanf 的返回值是「成功读到了几个数据」，可以用来判断用户有没有乱输。
     *         比如让人输数字，他偏要输字母，程序就会出错，所以要检查。
     *         这里把返回值存进 read_count 打出来，让你亲眼看到它是 1 还是 0。
     *         注意：这一段【不用】 if —— if 是第 4 课的内容，等学完再回来加上
     *         严格的校验（if (read_count != 1) { ... }）。
     *  新语法：scanf 的返回值、变量先给初值
     *  预期输出（输入 7）：
     *     请输入一个整数（试着输入字母看看会怎样）：scanf 读到了 1 个数据（1 = 输入正确，0 = 没读到数字）
     *     你输入的是 7，它的平方是 49。
     *     （如果输入字母 abc，「读到了几个数据」那里就会变成 0，
     *       而且 number 仍然是 0 —— 因为一个数都没读进来。）
     */
    int number = 0;
    int read_count = 0;
    printf("请输入一个整数（试着输入字母看看会怎样）：");

    read_count = scanf("%d", &number);
    /* 上面这一句的返回值，就是「成功读到了几个数据」。
     * 读到了 1 个 → 输入正常；读到了 0 个 → 用户压根没给出数字。
     * 这里先把返回值显示出来，第 4 课学会 if 之后，就可以在它不等于 1 时
     * 提示用户重输、或者直接 return 1 结束程序。 */

    printf("scanf 读到了 %d 个数据（1 = 输入正确，0 = 没读到数字）\n", read_count);
    printf("你输入的是 %d，它的平方是 %d。\n\n", number, number * number);

    /* ▶▶▶ 第 4 段：读一个单词
     *  做什么：方法一：%s —— 简单，但遇到空格就停下。
     *         读到的文字放进 word 数组，再数出它有几个字符。
     *         %49s 里的 49 是「最多读 49 个字符」：word 有 50 个位置，
     *         要留最后一个位置给结尾的 '\0'，所以最多只能读 49 个，
     *         这样用户就算手滑输入一长串，也撑不爆这个柜子。
     *  新语法：char 数组初始化、%s、%49s（带长度上限的 %s）、strlen
     *  预期输出（输入 hello）：
     *     请输入一个单词（不要有空格）：你输入的单词是 "hello"，长度 5。
     */
    /* 方法一：%s —— 简单，但遇到空格就停下 */
    char word[50] = {0};    /* 最多装 49 个字符 + 1 个结尾的 '\0' */
    printf("请输入一个单词（不要有空格）：");
    scanf("%49s", word);
    /* 注意这里没有 & —— 数组名本身就代表地址 */
    printf("你输入的单词是 \"%s\"，长度 %zu。\n\n", word, strlen(word));

    /* ▶▶▶ 第 5 段：读一整行（带空格的名字）
     *  做什么：方法二：fgets —— 可以读带空格的整行，推荐用它。
     *         先用一次 fgets 把上一行剩下的残余吃掉，
     *         再读你的全名，最后用 strcspn 去掉行末的换行符。
     *  新语法：fgets(缓冲区, 大小, stdin)、strcspn、'\0'
     *  预期输出（输入 Guo Daiyi）：
     *     请输入你的全名（可以带空格）：你好，Guo Daiyi！你的名字有 9 个字符。
     */
    /* 方法二：fgets —— 可以读带空格的整行，推荐用它 */
    char full_name[100] = {0};
    char leftover[100] = {0};

    /* 小坑：上一次 scanf 读完后，缓冲区里还留着一个换行符，
     *    fgets 会立刻把它读走，结果读到空字符串。
     *    所以先用一次 fgets 把那一行的残余吃掉： */
    fgets(leftover, sizeof(leftover), stdin);

    printf("请输入你的全名（可以带空格）：");
    fgets(full_name, sizeof(full_name), stdin);
    /* fgets 会把换行符也读进来，通常需要手动去掉末尾的换行符 */
    full_name[strcspn(full_name, "\n")] = '\0';
    printf("你好，%s！你的名字有 %zu 个字符。\n", full_name, strlen(full_name));

    return 0;
}

/* ============================================================================
 *  ▶ 动手练习（先自己做，卡住了再翻 CHEATSHEET.md，不要直接看答案）
 *  ---------------------------------------------------------------------------
 *  1) 写一个程序：问用户两个数字，输出它们的和、差、积、商。
 *     提示：注意检查除数是不是 0，是 0 就提示「除数不能为 0」。
 *     验收：输入 8 和 2 时，能同时看到和、差、积、商四个结果；除数为 0 时有专门提示。
 *
 *  2) 让用户输入圆的半径，输出周长和面积（保留 3 位小数）。
 *     提示：半径用 double 读，scanf 用 %lf，打印用 %.3f。
 *     验收：输入 2 时面积是 12.566（PI 可以用第 2 课那个 const 里的近似值）。
 *
 *  3) 把某个 scanf 的 & 删掉再运行，观察程序的表现（可能崩溃）。
 *     这就是为什么说「忘了 &」是新手第一号 bug。
 *     验收：亲眼看到异常现象，并且能解释「为什么少了 & 就会出事」。
 *
 *  4) 让用户输入自己的名字，然后输出「你好，XXX」。
 *     分别用 %s 和 fgets 写一遍，感受两者的区别。
 *     验收：输入「张 三」时，用 %s 的版本只读到「张」，fgets 的版本读到「张 三」。
 *
 *  5) 把第 3 段的判断改成「输入字母时不要退出，而是提示用户重输一次」。
 *     提示：先别急着写——这要用到 if（第 4 课）或者 while 循环（第 6 课）。
 *           这一课先做第一步就够了：把 scanf 的返回值打印出来，
 *           手动输入 abc，确认它变成 0。
 *     验收：输入 abc 时，屏幕上能看出「scanf 读到了 0 个数据」。
 *
 *  ▶ 本课常见报错速查
 *  ---------------------------------------------------------------------------
 *  （下面是 macOS 自带 clang 的原文；别的编译器措辞略有差别，意思一样）
 *
 *  warning: format specifies type 'int *' but the argument has type 'int'
 *      → scanf 里漏了 &（或者把 int 变量直接传了进去）。scanf 要地址，printf 才要值。
 *
 *  warning: format specifies type 'int *' but the argument has type 'double *'
 *      → 读 double 却用了 %d。scanf 读 double 必须写 %lf。
 *
 *  error: call to undeclared library function 'strlen' with type 'unsigned long (const char *)'
 *      → 忘了写 #include <string.h>。
 *
 *  Segmentation fault（段错误）
 *      → 十有八九是 scanf 少了 &。写成 scanf("%d", &n) 而不是 scanf("%d", n)。
 *        编译器有时只会给一个警告（warning: format specifies type 'int *' ...），
 *        但程序跑起来照样会崩，所以别把警告当没看见。
 *
 *  ▶ 自测题答案
 *  ---------------------------------------------------------------------------
 *  1) double 能装小数，int 只装整数。所以 1.75 必须用 double 装。
 *
 *  2) %d 是占位符，表示「这里请填一个整数」；逗号后面的 18 就是要填进去的值。
 *     几个占位符就按顺序填几个值。
 *
 *  3) 7 / 2 的结果是 3 —— 两个整数相除，小数部分被丢掉了。
 *     要 3.5 就写 7.0 / 2，或者 (double)7 / 2（只要有一边是小数就行）。
 *
 *  4) int 装得下（它最大能到 2147483647）。char 装不下（最大 127），
 *     硬装 200 会溢出，变成一个乱七八糟的数甚至负数。
 *
 *  ▶ 本课小结（能用自己的话说出来就算真的会了）
 *  ---------------------------------------------------------------------------
 *  · scanf 用法：scanf("格式", &变量1, &变量2, ...)
 *  · scanf 要「地址」（带 &），printf 要「值」（不带 &）——这是本课最该记住的一句
 *  · 读 double 用 %lf，打印 double 用 %f；长度用 %zu
 *  · scanf 的返回值 = 成功读到的数据个数，用它来做输入校验
 *  · %s 读单词（遇空格停）、fgets 读整行（带空格也行）
 *  · fgets 会把换行符读进来，用 strcspn + '\0' 去掉
 *  · 数组初始化写成 {0}，能避免残留的垃圾数据
 *
 *  ▶ 下一课预告
 *  ---------------------------------------------------------------------------
 *  第 4 课：条件判断 —— 目前程序都是「一条路走到底」，
 *  不管你输入什么它都照跑。这一课教它做选择：if / else if / else，
 *  以及最容易搞混的两组符号——比较运算符（==）和赋值（=）。
 * ============================================================================ */
