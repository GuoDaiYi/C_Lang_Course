/* ▶▶▶ 第 1 段：把取整工具请进来
 *  做什么：包含 stdio.h（输入输出）和 math.h（取整、取余这些数学函数）。
 *  新语法：#include <math.h>（第 13 课已经学过）
 *  预期输出：这一段不打印任何东西，只是让后面的代码认识 floor、ceil、round。
 */
#include <stdio.h>
#include <math.h>     /* floor ceil round trunc fmod */

int main(void) {

    /* ▶▶▶ 第 2 段：为什么需要取整（纯说明，这一段没有代码）
     *  做什么：解释现实里的数字为什么常常不能带小数。
     *  预期输出：这一段是纯文字说明，运行时不打印任何东西。
     *
     *  现实里的数经常不能带小数：
     *    分数 3/4 要写成 0.75，排名要写成第 3 名，账目要精确到分。
     *  C 提供了好几种取整方式，用途各不相同，选错就会出错。
     */

    /* ▶▶▶ 第 3 段：(int) 是「截断」，不是「四舍五入」
     *  做什么：把三个 double 强转成 int，观察小数部分是怎么被处理的。
     *  新语法：强制类型转换 (int)
     *  预期输出：
     *      --- 强制转换 (int) 的截断行为 ---
     *      (int) 3.9  = 3   <-- 朝 0 截，小数丢掉
     *      (int) -3.9 = -3   <-- 也朝 0 截！负数要特别注意！
     *      (int) 2.999= 2
     *
     *  把 double 变成 int 时，C 直接把小数部分扔掉，不管大小，
     *  而且【一律朝 0 的方向】扔：3.9 扔成 3，-3.9 也扔成 -3（不是 -4）。
     *
     *  如果你想的是「四舍五入」，(int) 3.9 = 3 就完全不对了。
     *  下面四种才是真正的取整函数。
     */
    printf("--- 强制转换 (int) 的截断行为 ---\n");
    printf("(int) 3.9  = %d   <-- 朝 0 截，小数丢掉\n", (int)3.9);
    printf("(int) -3.9 = %d   <-- 也朝 0 截！负数要特别注意！\n", (int)-3.9);
    printf("(int) 2.999= %d\n", (int)2.999);
    /* 如果你想的是「四舍五入」，(int) 3.9 = 3 就完全不对了。
     * 下面四种才是真正的取整函数。 */

    /* ▶▶▶ 第 4 段：四种取整函数对比
     *  做什么：用 6 个数（正负都有，还有两个 .5）跑一遍四种取整函数，
     *         打印成一张对照表。
     *  新语法：数组 + sizeof 求元素个数 + for 循环
     *  预期输出：
     *      --- 四种取整函数对比 ---
     *        原数      floor       ceil      round      trunc
     *         3.2        3.0        4.0        3.0        3.0
     *         3.8        3.0        4.0        4.0        3.0
     *        -3.2       -4.0       -3.0       -3.0       -3.0
     *        -3.8       -4.0       -3.0       -4.0       -3.0
     *         2.5        2.0        3.0        3.0        2.0
     *        -2.5       -3.0       -2.0       -3.0       -2.0
     *
     *  floor(x)  向下取整（地板）：往小的方向取
     *  ceil(x)   向上取整（天花板）：往大的方向取
     *  round(x)  四舍五入，.5 往【远离 0】的方向去
     *  trunc(x)  直接砍掉小数（朝 0 方向）
     *
     *  floor / ceil / round / trunc 返回的仍然是 double，
     *  想得到整数，自己再转一下。
     */
    printf("\n--- 四种取整函数对比 ---\n");
    double values[] = {3.2, 3.8, -3.2, -3.8, 2.5, -2.5};
    int count = sizeof(values) / sizeof(values[0]);

    printf("%8s %10s %10s %10s %10s\n",
           "原数", "floor", "ceil", "round", "trunc");
    for (int i = 0; i < count; i++) {
        double x = values[i];
        printf("%8.1f %10.1f %10.1f %10.1f %10.1f\n",
               x, floor(x), ceil(x), round(x), trunc(x));
    }
    /* 看懂这张表：
     *   3.2  -> floor 3,  ceil 4,  round 3,  trunc 3
     *   3.8  -> floor 3,  ceil 4,  round 4,  trunc 3
     *   -3.2 -> floor -4, ceil -3, round -3, trunc -3
     *   -3.8 -> floor -4, ceil -3, round -4, trunc -3
     *   2.5  -> round 3   （.5 远离 0，所以进位）
     *   -2.5 -> round -3  （.5 远离 0，所以也进位）
     * 负数是新手最容易错的地方，多打几遍这张表就记住了。
     * 记法：floor 是地板（永远在脚下，往小取），
     *       ceil 是天花板（永远在头顶，往大取），
     *       round 是「就近」，但遇到 .5 就往远离 0 的那边去。 */

    /* ▶▶▶ 第 5 段：取整 + 强制转换 = 整数结果
     *  做什么：拿价格 19.99 当例子，分别用 floor / ceil / round 得到整数。
     *  新语法：先调取整函数，再用 (int) 转成整数
     *  预期输出：
     *      --- 得到整数结果 ---
     *      价格 19.99
     *      floor 后转 int = 19
     *      ceil  后转 int = 20
     *      round 后转 int = 20
     *
     *  floor(3.8) 是个 double（3.0），要整数还得再转一次。
     *  ★ 注意：这里写 (int)floor(price) 是安全的，因为 floor 的结果
     *    本来就是整数值的 double，转成 int 不会丢东西。
     */
    printf("\n--- 得到整数结果 ---\n");
    double price = 19.99;
    printf("价格 %.2f\n", price);
    printf("floor 后转 int = %d\n", (int)floor(price));
    printf("ceil  后转 int = %d\n", (int)ceil(price));
    printf("round 后转 int = %d\n", (int)round(price));

    /* ▶▶▶ 第 6 段：fmod——浮点数的取余
     *  做什么：给三个小数做取余，看余数的符号跟谁走。
     *  新语法：fmod(被除数, 除数)
     *  预期输出：
     *      --- fmod 浮点取余 ---
     *      fmod(7.5, 2.0)  = 1.50   <-- 小数也能取余
     *      fmod(-7.5, 2.0) = -1.50   <-- 符号跟被除数走
     *      fmod(10.0, 3.0) = 1.00
     *
     *  整数取余用 %：7 % 2 = 1
     *  但 % 只能用于整数，7.5 % 2 会直接编译报错。
     *  小数取余要用 fmod(被除数, 除数)。
     *
     *  余数的符号跟【被除数】一致（和整数 % 一样）。
     *  应用：把时间换算成「几小时几分钟」、
     *        把角度归一化（第 14 课就用到了）。
     */
    printf("\n--- fmod 浮点取余 ---\n");
    printf("fmod(7.5, 2.0)  = %.2f   <-- 小数也能取余\n", fmod(7.5, 2.0));
    printf("fmod(-7.5, 2.0) = %.2f   <-- 符号跟被除数走\n", fmod(-7.5, 2.0));
    printf("fmod(10.0, 3.0) = %.2f\n", fmod(10.0, 3.0));
    /* 应用：把时间换算成「几小时几分钟」、
     *       把角度归一化（第 14 课就用到了）。 */

    /* ▶▶▶ 第 7 段：保留两位小数的两种写法
     *  做什么：同一个数 3.14159265，用「只格式化打印」和「真的四舍五入」
     *         两种办法处理，再各自乘 3 看差别。
     *  新语法：round(x * 100.0) / 100.0
     *  预期输出：
     *      --- 保留两位小数 ---
     *      原值                = 3.141593
     *      只格式化打印        = 3.14   <-- 值本身没变
     *      四舍五入后的值      = 3.140000   <-- 值真的变了
     *      拿它继续乘 3       = 9.420000
     *      （如果用格式化打印的那个值乘 3，会是 9.424778）
     *
     *  写法一：printf("%.2f", x)
     *    只在【打印的时候】把小数显示成两位，变量本身没变。
     *
     *  写法二：round(x * 100.0) / 100.0
     *    真正把数值本身变成两位小数，可以拿去继续计算。
     *
     *  要参与后续计算，就用第二种写法。
     */
    printf("\n--- 保留两位小数 ---\n");
    double raw = 3.14159265;

    printf("原值                = %f\n", raw);
    printf("只格式化打印        = %.2f   <-- 值本身没变\n", raw);
    printf("四舍五入后的值      = %f   <-- 值真的变了\n",
           round(raw * 100.0) / 100.0);

    double result = round(raw * 100.0) / 100.0;
    printf("拿它继续乘 3       = %f\n", result * 3.0);
    printf("（如果用格式化打印的那个值乘 3，会是 %f）\n",
           3.14159265 * 3.0);
    /* 要参与后续计算，就用第二种写法。 */

    /* ▶▶▶ 第 8 段：坑——浮点数算钱不精确
     *  做什么：算 0.1 + 0.2，打印到小数点后 20 位，再比较它和 0.3 是否相等。
     *  新语法：fabs()、1e-9 这种科学计数法
     *  预期输出：
     *      --- 浮点数精度问题 ---
     *      0.1 + 0.2         = 0.30000000000000004441
     *      判断 sum == 0.3    = false
     *      用 epsilon 比较    = 一样（这是实际项目里的常用写法）
     *      用分计算：1999 分 × 3 = 5997 分 = 59.97 元
     *
     *  0.1 和 0.2 在计算机里其实存的是无限接近这两个数的
     *  二进制小数，所以相加会多出一点点。
     *
     *  结果是 false！看起来一样的两个数比较起来不相等。
     *
     *  两种常见解决办法：
     *    1) 比较时留一点误差范围（下面那个 epsilon 的写法）；
     *    2) 算钱用整数：以「分」为单位存，最后再除以 100。
     */
    printf("\n--- 浮点数精度问题 ---\n");
    double sum = 0.1 + 0.2;
    printf("0.1 + 0.2         = %.20f\n", sum);
    printf("判断 sum == 0.3    = %s\n", (sum == 0.3) ? "true" : "false");
    /* 结果是 false！看起来一样的两个数比较起来不相等。
     *
     * 两种常见解决办法：
     *   1) 比较时留一点误差范围（下面那个 epsilon 的写法）；
     *   2) 算钱用整数：以「分」为单位存，最后再除以 100。 */

    /* epsilon = 一个非常小的数，表示「允许的误差范围」 */
    const double epsilon = 1e-9;
    if (fabs(sum - 0.3) < epsilon) {
        printf("用 epsilon 比较    = 一样（这是实际项目里的常用写法）\n");
    }

    /* 以分为单位算钱，一分不差 */
    int price_cents = 1999;            /* 19.99 元 = 1999 分 */
    int quantity = 3;
    int total_cents = price_cents * quantity;
    printf("用分计算：%d 分 × %d = %d 分 = %d.%02d 元\n",
           price_cents, quantity, total_cents,
           total_cents / 100, total_cents % 100);

    return 0;
}

