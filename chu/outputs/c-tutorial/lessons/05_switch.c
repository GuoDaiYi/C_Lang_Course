/*
 * ============================================================================
 *  第 5 课：多分支选择（switch / case）
 * ============================================================================
 *
 *  ▶ 这节课要解决什么问题
 *  ---------------------------------------------------------------------------
 *    第 4 课的 if 已经能应付大多数选择了。但如果条件是
 *    「这个数等于 1 就这样，等于 2 就那样，等于 3 就另一个样子」，
 *    我们就得写一长串 if / else if / else if / else if……越写越长。
 *
 *    这一课解决的，就是这个场景：换一种更整齐的写法。
 *    打个比方：if 像连环追问——「你是 1 吗？不是？那你是 2 吗？还不是？」
 *    switch 像查字典——「直接翻到 2 那一页」。两种都能找到答案，
 *    但查字典在选项多的时候明显更清爽。
 *
 *    学完这节课，你能：
 *      · 用 switch / case 把「一个值等于几」的分支写得一清二楚；
 *      · 知道 break 忘写会发生什么（贯穿执行），以及它其实是能用的；
 *      · 会用 default 兜底，不会让程序遇到意外输入时一声不吭；
 *      · 学会「switch 还是 if」的判断标准。
 *
 *  ▶ 学这节课之前，你需要已经会（前置知识）
 *  ---------------------------------------------------------------------------
 *    ✅ 已经会：第 1 课：第一个 C 程序
 *       （会写 main、每条语句加分号、会用 printf 打印）
 *    ✅ 已经会：第 2 课：变量与数据类型
 *       （会声明 int / double / char、知道格式符要和类型对上）
 *    ✅ 已经会：第 3 课：让程序会问问题（输入）
 *       （会用 scanf 读数、知道读 double 要写 %lf、知道 scanf 的返回值）
 *    ✅ 已经会：第 4 课：条件判断
 *       （会用 if / else if / else、懂 == 和 = 的区别、会用 && || !）
 *    🔁 忘了就看：第 4 课「第 3 段」的 if / else if / else 写法，
 *       和第 4 课文件末尾「本课小结」里的 if 与 switch 的分工。
 *    ❓ 开课自测（这 4 题能答上来再往下学，答案在文件最末尾）
 *       1) 判断「a 等于 5」，应该写 = 还是 ==？两者含义有什么不同？
 *       2) if (x > 1 && x < 10) 能不能写成 if (1 < x < 10)？
 *       3) C 里 0 和 1 分别代表什么？-1 算真还是算假？
 *       4) printf("%d", 42) 里的 %d 是干什么用的？
 *
 *  ▶ 本节课新出现的语法（先扫一眼这张表，看不懂的先跳过，学到自然会懂）
 *  ---------------------------------------------------------------------------
 *    1) switch (表达式) { ... }
 *       写法：switch (choice) { case 1: ...; break; default: ...; }
 *       读作：开关（要判断的那个值）{ 分支 }
 *       作用：按「这个值等于几」来分流。
 *       注意：括号里的东西必须是【整数类型】——int 行，char 也行，double 不行。
 *             程序是从上往下找，找到和它相等的 case，就从那里开始往下执行。
 *
 *    2) case 常量:
 *       写法：case 1:   case 'A':
 *       读作：情况是 1 / 情况是字母 A
 *       作用：列出 switch 支持的每一种可能取值。
 *       注意：case 后面只能跟【常量】，不能跟变量。
 *             写成 case x: 编译器会报 case label does not reduce to a constant expression。
 *
 *    3) break;
 *       读作：跳出
 *       作用：这一段做完了，离开 switch。
 *       注意：这是本课头号坑。漏掉 break，程序会顺着往下把后面的 case 也执行一遍
 *             （这种现象叫「贯穿执行」）。
 *             初学阶段记住：每个 case 结尾都写 break；
 *             最后一个 case（通常是 default）的 break 可以省略。
 *
 *    4) default:
 *       读作：默认
 *       作用：上面所有 case 都不匹配时，走这一段。
 *       注意：写不写都行，但不写的话，用户输入意外的值，程序什么也不做，
 *             看起来就像坏了。所以建议一定写一个 default。
 *             它放在 switch 的哪个位置都可以，习惯上放最后。
 *
 *    5) 多个 case 共用一段代码
 *       写法：
 *         case 6:
 *         case 7:
 *         case 8:
 *             printf("暑假\n");
 *             break;
 *       作用：几个取值共用同一段处理逻辑。
 *       注意：这里的「漏掉 break」是故意要的，不是写错。
 *             6、7、8 三个月共用「暑假」这段代码，遇到其中任何一个，
 *             都会一路走到 printf 那里，再由 break 收尾。
 *
 *    6) switch 处理字符
 *       写法：char key = 'B';  switch (key) { case 'B': ... }
 *       作用：字符也能用 switch 分流，常见于菜单按键处理。
 *       注意：字符要写在单引号里；大小写各写一个 case 是最常见的写法。
 *
 *    7) switch 里也可以写 if
 *       写法：
 *         case '/':
 *             if (b == 0.0) { printf("除数不能是 0\n"); }
 *             else { printf("%.2f\n", a / b); }
 *             break;
 *       作用：某个分支内部还有条件要判断时，直接写 if。
 *       注意：别忘了这个分支最后的 break。
 *
 *    8) 本课先「不出现」的东西（后面几课才正式登场，这里只做预告）
 *       · 函数（第 7 课）：可以把一串 case 装成一个函数
 *       · 循环（第 6 课）：让菜单一直转下去、让同一段代码重复执行
 *       · 数组（第 8 课）：一次装好一排数据
 *       本课的代码里刻意不用它们，保证你看到的每一个语法，
 *       都是前面几课已经学过的。相关代码以「预告」的形式写在注释里。
 *
 *  ▶ 怎么读这个文件
 *  ---------------------------------------------------------------------------
 *    1. 先读完上面几块（问题 / 前置 / 新语法），心里有框架；
 *    2. 往下看代码，每段前面有「▶▶▶ 第 N 段」，讲清这段在干嘛、跑起来看到什么；
 *    3. 边看边预演输出——特别留意「漏掉 break」那一段的输出；
 *    4. 最后做「动手练习」和「自测题」。
 *
 *  运行方式（在本项目根目录下）：
 *    make run L=lessons/05_switch
 *    或者手动：cc lessons/05_switch.c -o demo && ./demo
 *    第 10 段的简易计算器需要你手动输入，运行后按提示敲键盘再回车。
 * ============================================================================
 */

#include <stdio.h>

int main(void) {

    /* ▶▶▶ 第 1 段：为什么需要 switch
     *  做什么：上一课我们用 if / else if 写过一个菜单。
     *         如果菜单有 8 个选项，就要写 8 次「如果它等于几」：
     *
     *   if (choice == 1) { ... }
     *   else if (choice == 2) { ... }
     *   else if (choice == 3) { ... }
     *   ...
     *
     * 条件都是「等于某个具体值」时，switch 写起来短得多，也更好读。
     * 记住一句话：switch 处理「一个值等于几」，if 处理「条件成不成立」。
     *  新语法：这一段只是对比说明，还没有新语法。
     *  预期输出：本段不输出任何内容。
     */

    /* ▶▶▶ 第 2 段：switch 的基本写法
     *  做什么：choice 是 2，程序从上往下找 case，
     *         找到 case 2 就执行「读取存档」，然后遇到 break 跳出 switch。
     *  新语法：switch / case / break / default
     *  预期输出：
     *     --- 菜单选择 2 ---
     *     读取存档
     */
    int choice = 2;
    printf("--- 菜单选择 %d ---\n", choice);

    switch (choice) {
        case 1:
            printf("开始新游戏\n");
            break;
        case 2:
            printf("读取存档\n");
            break;
        case 3:
            printf("设置\n");
            break;
        default:
            printf("无效选项\n");
            break;
    }
    /* 三个要点：
     *   switch (表达式)   要判断的那个值，必须是整数类型（int、char 都可以）
     *   case 常量:        一个一个列出可能的取值，常量不能是变量
     *   break;            这一段做完了，跳出 switch
     * 程序从上往下找，找到和表达式相等的 case，就从那里开始往下执行。 */

    /* ▶▶▶ 第 3 段：break —— 漏掉会发生什么
     *  做什么：n 是 2。找到 case 2 后打印一句话，
     *         但 case 2 后面【故意】没写 break，
     *         于是程序顺着往下把 case 3 也执行了。
     *  新语法：没有新语法，重点是「不写 break」的后果
     *  预期输出：
     *     --- 漏掉 break 的后果 ---
     *     这是 case 2
     *     这是 case 3
     */
    printf("\n--- 漏掉 break 的后果 ---\n");
    int n = 2;
    switch (n) {
        case 1:
            printf("这是 case 1\n");
        case 2:
            printf("这是 case 2\n");
        case 3:
            printf("这是 case 3\n");
    }
    /* 上面只打印了两句：case 2 和 case 3。
     * 因为 case 2 后面没有 break，程序会顺着往下继续执行，
     * 这种现象叫「贯穿执行」（fall-through）。
     *
     * 所以初学阶段，记住一句话：每个 case 结尾都写 break；
     * 最后一个 case（通常是 default）的 break 可以省略。 */

    /* ▶▶▶ 第 4 段：多个 case 共用一段代码
     *  做什么：month 是 7。程序先匹配 case 6（不匹配）、
     *         再匹配 case 7（匹配），于是从 case 7 往下走，
     *         走到 printf 那句打印「暑假」，再由 break 收尾。
     *  新语法：多个 case 连着写，共用一段代码
     *  预期输出：
     *     --- 多个 case 共用一段代码 ---
     *     7 月：暑假
     */
    printf("\n--- 多个 case 共用一段代码 ---\n");
    int month = 7;
    switch (month) {
        case 6:
        case 7:
        case 8:
            printf("%d 月：暑假\n", month);
            break;
        case 9:
        case 10:
        case 11:
            printf("%d 月：开学了\n", month);
            break;
        default:
            printf("%d 月：上学的日子\n", month);
            break;
    }
    /* 这里的贯穿执行是我们故意要的：
     * 6、7、8 三个月共用「暑假」这段代码，
     * 遇到其中任何一个，都会一路走到 printf 那里，再由 break 收尾。 */

    /* ▶▶▶ 第 5 段：default —— 兜底分支
     *  做什么：wrong_choice 是 9，switch 里只有 case 1，
     *         9 谁都匹配不上，于是走 default 这条兜底的路。
     *  新语法：default 分支
     *  预期输出：
     *     --- default 兜底 ---
     *     无效选项 9
     */
    printf("\n--- default 兜底 ---\n");
    int wrong_choice = 9;
    switch (wrong_choice) {
        case 1:
            printf("开始新游戏\n");
            break;
        default:
            printf("无效选项 %d\n", wrong_choice);
            break;
    }
    /* default 表示「上面所有 case 都不匹配时执行的代码」。
     * 写不写都可以，但不写的话，用户输入了意外的值，程序什么也不做，
     * 看起来就像坏了。所以建议一定写一个 default。
     *
     * default 放在 switch 的哪个位置都可以（case 写在 default 后面也合法），
     * 但习惯上放在最后面。 */

    /* ▶▶▶ 第 6 段：把「星期几」翻译成中文
     *  做什么：day 是 3，switch 找到 case 3，打印「星期三」。
     *         每个 case 各自打印自己那一句话，这是最直白的 switch 用法。
     *  新语法：没有新语法，本段是把第 2 段的写法用熟
     *  预期输出：
     *     --- 星期几 ---
     *     星期三
     */
    printf("\n--- 星期几 ---\n");
    int day = 3;
    switch (day) {
        case 1:
            printf("星期一\n");
            break;
        case 2:
            printf("星期二\n");
            break;
        case 3:
            printf("星期三\n");
            break;
        case 4:
            printf("星期四\n");
            break;
        case 5:
            printf("星期五\n");
            break;
        case 6:
            printf("星期六\n");
            break;
        case 7:
            printf("星期日\n");
            break;
        default:
            printf("这不是一个星期几\n");
            break;
    }
    /* 预告：等你学过第 7 课（函数）之后，可以把上面这一整串装进一个函数，
     * 每个 case 后面直接写 return：
     *
     *   const char *weekday_name(int day) {
     *       switch (day) {
     *           case 1:  return "星期一";
     *           case 2:  return "星期二";
     *           ...
     *           default: return "这不是一个星期几";
     *       }
     *   }
     *
     * 每个 case 后面直接 return，函数就结束了，
     * 所以这种写法不需要 break，写起来比一长串 if 短得多。 */

    /* ▶▶▶ 第 7 段：用 switch 处理字符
     *  做什么：key 是大写字母 B，匹配到 case 'B'，打印「你选了 B：删除」。
     *         大写 B 和小写 b 分成两个 case，谁都能用。
     *  新语法：char 也能当 switch 的判断对象
     *  预期输出：
     *     --- 用 switch 处理字符 ---
     *     你选了 B：删除
     */
    printf("\n--- 用 switch 处理字符 ---\n");
    char key = 'B';
    switch (key) {
        case 'A':
        case 'a':
            printf("你选了 A：新增\n");
            break;
        case 'B':
        case 'b':
            printf("你选了 B：删除\n");
            break;
        case 'Q':
        case 'q':
            printf("退出\n");
            break;
        default:
            printf("未知按键 %c\n", key);
            break;
    }
    /* 字符要写在单引号里，和字符串的双引号不一样。
     * 大小写各写一个 case，是最常见的写法。 */

    /* ▶▶▶ 第 8 段：switch 和 if 怎么选
     *  做什么：score 是 76，走 else if (score >= 60) 那条路，判成 C。
     *  新语法：没有新语法，本段是和 if 的对照
     *  预期输出：
     *     --- 判断范围只能用 if ---
     *     等级 C
     */
    int score = 76;
    printf("\n--- 判断范围只能用 if ---\n");

    if (score >= 90) {
        printf("等级 A\n");
    } else if (score >= 60) {
        printf("等级 C\n");
    } else {
        printf("等级 F\n");
    }
    /* 上面这种「比大小」的条件，switch 写不了，
     * 因为 case 后面只能跟固定的值，没法写 score >= 90。
     *
     * 简单对照：
     *   条件是「等于某个值」   -> switch 更清爽
     *   条件是「范围、大小」   -> 只能用 if
     *   条件是「多个条件组合」 -> 只能用 if */

    /* ▶▶▶ 第 9 段：循环里的 switch（先看一眼形状）
     *  做什么：这一段现在只做「预告」，代码先不写进程序里。
     *         等第 6 课学了循环，真实的菜单程序 = 循环 + switch：
     *         循环负责「一直转下去」，switch 负责「这一次做哪件事」。
     *
     *   int orders[] = {1, 3, 2, 9};
     *   for (int i = 0; i < 4; i++) {
     *       printf("选择 %d -> ", orders[i]);
     *       switch (orders[i]) {
     *           case 1: printf("新增一条记录\n"); break;
     *           case 2: printf("查看全部记录\n"); break;
     *           case 3: printf("保存到文件\n");   break;
     *           default: printf("没有这个选项\n"); break;
     *       }
     *   }
     *
     * 这个「循环 + switch」的结构，就是 projects/grade_book.c 的骨架。
     *  新语法：没有新语法，本段是给第 6 课的预告
     *  预期输出：本段不输出任何内容（循环第 6 课才学）。
     */

    /* ▶▶▶ 第 10 段：实战 —— 简易计算器
     *  做什么：让你输入两个数和一个运算符，程序算出结果。
     *         scanf("%lf %c %lf", ...) 一次读三个：数、运算符、数。
     *         格式串里 %c 前面那个空格有讲究：它让 scanf 先跳过所有空白字符，
     *         所以你输入「3 + 2」时，那个空格不会跑到 op 里去。
     *         switch 把运算符分派到不同的算式；除法分支里再用 if 检查除数是不是 0。
     *  新语法：scanf 读多个值、switch 里嵌套 if
     *  预期输出（输入 3 + 2）：
     *     --- 简易计算器（需要你输入）---
     *     请输入两个数和一个运算符（例如 3 + 2）：3.00 + 2.00 = 5.00
     */
    printf("\n--- 简易计算器（需要你输入）---\n");
    printf("请输入两个数和一个运算符（例如 3 + 2）：");

    double a = 0.0;
    double b = 0.0;
    char op = '+';

    if (scanf("%lf %c %lf", &a, &op, &b) != 3) {
        printf("输入格式不对，应该像「3 + 2」这样。\n");
        return 1;
    }

    switch (op) {
        case '+':
            printf("%.2f + %.2f = %.2f\n", a, b, a + b);
            break;
        case '-':
            printf("%.2f - %.2f = %.2f\n", a, b, a - b);
            break;
        case '*':
            printf("%.2f * %.2f = %.2f\n", a, b, a * b);
            break;
        case '/':
            if (b == 0.0) {
                printf("除数不能是 0\n");
            } else {
                printf("%.2f / %.2f = %.2f\n", a, b, a / b);
            }
            break;
        default:
            printf("我不认识运算符 %c\n", op);
            break;
    }
    /* 这个计算器用 if 也能写，但运算符是「+ - * /」四种固定取值时，
     * switch 明显更整齐：一眼就能看出支持哪几种运算。 */

    /* ▶▶▶ 第 11 段：常见错误清单
     *  做什么：这一段全是注释，列的都是写 switch 时真的会踩的坑。
     *         读完这一段，你踩坑的概率会小一大半。
     *  新语法：没有新语法，本段是避坑清单
     *  预期输出：本段不输出任何内容（清单全在注释里）。
     */
    /* 1) case 后面必须是常量，不能写变量：
     *      int x = 2;
     *      switch (x) { case x: ... }     <- 编译报错
     *
     * 2) switch 括号里必须是整数类型：
     *      switch (3.14) { ... }          <- 编译报错
     *      switch ("abc") { ... }         <- 编译报错
     *
     * 3) 同一个 switch 里不能有两个相同的 case：
     *      case 1: ...  case 1: ...       <- 编译报错
     *
     * 4) 最常见的错：忘写 break。程序不会报错，但会多执行下面的 case，
     *    表现是「选项 2 打印了选项 3 的内容」。
     *
     * 5) switch 里的 break 只跳出 switch，跳不出外面的循环。
     *    也就是说，一旦 switch 写在循环里面，循环照样会转下一圈：
     *
     *      for (int i = 1; i <= 3; i++) {
     *          switch (i) {
     *              case 2:
     *                  printf("i = %d：只跳出 switch，循环继续\n", i);
     *                  break;
     *              default:
     *                  printf("i = %d：普通的一轮\n", i);
     *                  break;
     *          }
     *      }
     *
     *    上面这段会完整转 3 圈，每圈打印一行。循环是第 6 课的内容，
     *    现在只要记住结论就行：想跳出循环，得在循环里写 break，
     *    光在 switch 里写 break 是没用的。 */

    return 0;
}

