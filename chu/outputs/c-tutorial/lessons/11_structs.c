/*
 * ============================================================================
 *  第 11 课：结构体（把一组相关数据打包成一个整体）
 * ============================================================================
 *
 *  本课知识点：struct 定义、typedef、初始化、用 . 访问成员、
 *              结构体数组、用 -> 通过指针访问、把结构体传给函数
 *
 *  ▶ 这节课要解决什么问题
 *  ---------------------------------------------------------------------------
 *    看一张学生成绩单：每一行永远是「姓名 + 学号 + 成绩」三样东西绑在一起，
 *    拆开就没意义了。
 *
 *    但是数组（第 8 课）有个硬规定：一个数组里只能放同一种类型的数据。
 *    你不能一个数组里放名字、另一个数组放学号——那样三个数组就得分头维护，
 *    姓名和成绩就对不上号了。
 *
 *    结构体就是来解决这件事的：让程序员自己造一个「新类型」，
 *    这个类型里可以装名字（文字）、学号（数字）、成绩（数字），
 *    打包成整体一起存、一起取。
 *
 *    学完这一课你能做到：
 *      1) 定义一个属于自己的类型，把几样数据打包在一起；
 *      2) 用结构体数组做出一张成绩单，并且能遍历它；
 *      3) 分清什么时候用「点 .」，什么时候用「箭头 ->」；
 *      4) 让函数接收、修改、甚至返回一整包数据。
 *
 *  ▶ 学这节课之前，你需要已经会（前置知识）
 *  ---------------------------------------------------------------------------
 *    ✅ 已经会：第 8 课：数组（会声明、初始化、for 循环遍历、知道下标从 0 开始）
 *    ✅ 已经会：第 9 课：字符串（会用 char name[20]、会用 strcpy 往字符数组里放名字）
 *    ✅ 已经会：第 10 课：指针（会用 & 取地址、* 解引用，知道 int *p 怎么读）
 *    ✅ 已经会：第 7 课：函数（会声明函数、会传参数、知道参数可以是数组和指针）
 *    🔁 忘了就看：第 9 课「字符数组不能用 = 赋值，要用 strcpy」
 *    🔁 忘了就看：第 10 课「同一个 * 在声明时是「指针」，使用时是「解引用」」
 *    🔁 忘了就看：第 8 课「sizeof(数组) / sizeof(数组[0]) = 元素个数」
 *    ❓ 开课自测（4 题，能答上来再往下学；答案在文件最末尾）
 *       1) 为什么不能直接用 int 数组来存「姓名 + 成绩」这种成组的数据？
 *       2) 一个结构体类型和一个结构体变量有什么区别？
 *       3) 已知 struct Student s; 想访问里面的 id 成员，写什么？
 *       4) 如果手上拿的是地址（Student *p），访问成员又要写什么？
 *
 *  ▶ 本节课新出现的语法（先扫一眼这张表，看不懂的先跳过，学到自然会懂）
 *  ---------------------------------------------------------------------------
 *    1) struct（结构体关键字）
 *       读作：结 构 体
 *       作用：告诉编译器「我要定义一个由多个成员组成的新类型」。
 *       注意：struct 是类型（说明书），不是变量（盒子）。
 *             有了 struct Student 这个类型，还得写 Student s; 才有变量。
 *
 *    2) typedef struct { ... } Student;
 *       读作：把「结构体 Student」起个简称 Student
 *       作用：typedef 是「给类型起别名」的关键字。
 *             有了它，后面写 Student 就等于写 struct Student，省事又好看。
 *       注意：这一整句只在「类型说明」的位置出现一次，
 *             而且必须放在 main 之前（因为 main 里要拿它当类型用）。
 *
 *    3) 成员声明 char name[20];  int id;
 *       读作：成员 name 是 20 个字符的数组，成员 id 是整数
 *       作用：说明这个新类型由哪几样东西组成。
 *       注意：成员之间用分号结尾；数组要写清长度 [20]。
 *
 *    4) Student s;  /  Student s = {"小红", 1002, 95};
 *       读作：声明一个叫 s 的 Student；或者直接给它一个初始值
 *       作用：创建结构体变量。初始化时按成员的先后顺序一个一个填。
 *       注意：一次要填齐所有成员，顺序不能错；
 *             只填一部分的话，剩下的会被自动置 0。
 *
 *    5) s.name  （用「点」访问成员）
 *       读作：s 的 name
 *       作用：取出或修改成员的值。s 是变量本身，所以用点。
 *       注意：点的前面必须是「结构体变量」，不能是地址。
 *
 *    6) p->name  （用「箭头」访问成员）
 *       读作：p 指向的那个结构体的 name
 *       作用：p 是指针（手里拿着地址），所以用箭头。
 *       注意：箭头可以理解成「先 * 解引用，再用点」，即 p->name 等价于 (*p).name，
 *             但箭头写起来短得多，是官方推荐写法。
 *       记忆口诀：**手里是变量用点，手里是地址用箭头**。
 *
 *    7) 指定成员初始化 Student d = {.score = 60, .name = "小美"};
 *       读作：把 score 设成 60、name 设成 "小美"，没写的 id 自动为 0
 *       作用：初始化时只写你关心的成员，顺序随便放，可读性最好。
 *       注意：成员名前要加点，值之间用逗号分隔。这是 C99 才有的写法。
 *
 *    8) sizeof(class3) / sizeof(class3[0])
 *       读作：整个数组占多少字节，除以一个元素占多少字节
 *       作用：算出数组里有多少个元素。这招在第 8 课出现过，这里再复习一次。
 *       注意：分母是「一个元素的大小」，不是「整个数组的大小」，
 *             除完才是元素个数。
 *
 *    9) %zu
 *       读作：按 size_t（无符号整数）打印
 *       作用：sizeof 的结果类型是 size_t，打印它必须用 %zu，
 *             用 %d 属于类型不匹配（编译器会警告）。
 *       注意：%zu 里的 z 就是 size_t 的 z。
 *
 *    10) %-8s  /  %-8d
 *       读作：左对齐、字段宽度 8
 *       作用：%-8s 把字符串按 8 格宽度左对齐输出，做表格时列就对齐了。
 *       注意：负号表示左对齐（默认是右对齐）；8 是总宽度，不够会补空格。
 *
 *    11) const Student list[]
 *       读作：只读的学生数组
 *       作用：告诉编译器「这个函数只看这个数组，不会改它」。
 *       注意：const 是第 10 课学过的那把锁，用法完全一样。
 *
 *    12) strcpy(a.name, "小明")
 *       读作：把 "小明" 拷贝进 a.name
 *       作用：往字符数组里放名字。
 *       注意：字符数组不能用 = 赋值（a.name = "小明" 是错的），
 *             必须用 strcpy，而且目标数组要够大（第 9 课学过）。
 *
 *  ▶ 怎么读这个文件
 *  ---------------------------------------------------------------------------
 *    1. 先读完上面这三块（问题 / 前置 / 新语法），心里先有个框架；
 *    2. 往下看代码，每段代码前面都有「▶▶▶ 第 N 段」，讲清这段在干嘛、
 *       跑起来会看到什么；
 *    3. 边看边在脑子里预演输出，觉得「我大概知道这段会打印什么」再往下走；
 *    4. 最后做「动手练习」和「自测题」。
 *
 *  运行方式（在本项目根目录下）：
 *    make run L=lessons/11_structs
 *    或者手动：cc lessons/11_structs.c -o demo && ./demo
 * ============================================================================ */

#include <stdio.h>
#include <string.h>

/* ============================================================
 * 一、定义一种新类型：学生
 * ------------------------------------------------------------
 * 现实里的「学生」不是单个数字，而是「姓名 + 学号 + 成绩」的组合。
 * 结构体就是让程序员自己造类型的工具。
 *
 * typedef struct { ... } Student; 的意思是：
 *   以后写 Student 就等于写 struct Student，省事又好看。
 * ============================================================ */
typedef struct {
    char  name[20];     /* 姓名 */
    int   id;           /* 学号 */
    int   score;        /* 成绩 */
} Student;

/* 结构体也可以嵌套：日期里面又有年月日 */
typedef struct {
    int year;
    int month;
    int day;
} Date;

typedef struct {
    char name[20];
    Date birthday;      /* 成员本身又是一个结构体 */
} Person;

/* 函数声明 */
void print_student(Student s);                 /* 传值：给的是拷贝 */
void raise_score(Student *s, int delta);       /* 传指针：能改到原件 */
double average_score(const Student list[], int count);
Student find_top(const Student list[], int count);

int main(void) {

    /* ▶▶▶ 第 1 段：创建结构体变量并给它的成员赋值
     *  做什么：声明一个叫 xiaoming 的 Student，
     *          分别往它的三个成员（姓名、学号、成绩）里塞值，然后整条打印。
     *  新语法：Student xiaoming;、strcpy、s.name / s.id / s.score
     *  预期输出：
     *      姓名: 小明, 学号: 1001, 成绩: 88
     */
    Student xiaoming;
    /* 用「点」访问成员 */
    strcpy(xiaoming.name, "小明");     /* 字符数组不能用 = 赋值，要用 strcpy */
    xiaoming.id = 1001;
    xiaoming.score = 88;

    printf("姓名: %s, 学号: %d, 成绩: %d\n",
           xiaoming.name, xiaoming.id, xiaoming.score);

    /* ▶▶▶ 第 2 段：声明时直接初始化 —— 一次性填齐全部成员
     *  做什么：直接写出姓名、学号、成绩，一次搞定，不用一行行赋值。
     *          再演示一种「指定成员初始化」的写法，顺序可以乱写，
     *          没提到的成员自动补 0。
     *  新语法：Student s = {"小红", 1002, 95};、
     *          Student s = {.score = 60, .name = "小美", .id = 1004};
     *  预期输出：这一段只赋值不打印，所以屏幕上没有新内容。
     *            （三个变量的内容分别是 小红95 / 小刚72 / 小美60-小美1004，
     *              下一段打印时会看到）
     */
    Student xiaohong = {"小红", 1002, 95};
    Student xiaogang = {"小刚", 1003, 72};

    /* 指定成员初始化的写法（可读性更好） */
    Student xiaomei = {.score = 60, .name = "小美", .id = 1004};

    /* ▶▶▶ 第 3 段：把结构体交给函数 —— 传值 vs 传指针
     *  做什么：先让函数打印三个学生的信息；
     *          然后做对比实验：先把 xiaogang 拷贝一份给 copy，
     *          给 copy 加分（原件不变）；再直接给 xiaogang 加分（原件真的变了）。
     *  新语法：结构体整体赋值 Student copy = xiaogang;、传地址 &xiaogang
     *  预期输出：
     *      （空行）
     *      --- 打印学生 ---
     *      姓名: 小红 学号: 1002   成绩: 95
     *      姓名: 小刚 学号: 1003   成绩: 72
     *      姓名: 小美 学号: 1004   成绩: 60
     *      （空行）
     *      加 10 分（传值，改不了原数据）：copy 现在的分数 82，而原来的 xiaogang 还是 72
     *      用 &xiaogang 之后，xiaogang 的分数真的变成了 82
     *    关键点：两次都是「加 10 分」，但一次改了副本，一次改了原件——
     *            区别只在于传的是值还是地址（第 10 课讲的老道理）。
     */
    printf("\n--- 打印学生 ---\n");
    print_student(xiaohong);
    print_student(xiaogang);
    print_student(xiaomei);

    /* 传值 vs 传指针，区别很关键 */
    const int bonus = 10;             /* 要加的分数，起个名字 */
    printf("\n加 %d 分（传值，改不了原数据）：", bonus);
    Student copy = xiaogang;          /* 整体拷贝一份，copy 和 xiaogang 长得一样 */
    raise_score(&copy, bonus);         /* 传址给 copy 的副本 */
    printf("copy 现在的分数 %d，而原来的 xiaogang 还是 %d\n",
           copy.score, xiaogang.score);

    /* 传值的方式（下面这行如果传 xiaogang 而不是 &xiaogang，原数据不会被改） */
    raise_score(&xiaogang, bonus);
    printf("用 &xiaogang 之后，xiaogang 的分数真的变成了 %d\n", xiaogang.score);

    /* ▶▶▶ 第 4 段：结构体数组 —— 像一张真正的成绩单
     *  做什么：用一个结构体数组存全班 5 个学生，
     *          用 sizeof 算出人数，再用 for 循环把整张表打印出来。
     *  新语法：Student class3[] = { {...}, {...} };、
     *          sizeof(class3) / sizeof(class3[0])、class3[i].name
     *  预期输出：
     *      （空行）
     *      --- 全班成绩单 ---
     *      姓名   学号   成绩
     *      小明   1001     88
     *      小红   1002     95
     *      小刚   1003     72
     *      小美   1004     60
     *      小强   1005     79
     *      （空行）
     *      班级平均分 = 78.80
     *      第一名: 小红（95 分）
     */
    Student class3[] = {
        {"小明", 1001, 88},
        {"小红", 1002, 95},
        {"小刚", 1003, 72},
        {"小美", 1004, 60},
        {"小强", 1005, 79}
    };
    int count = sizeof(class3) / sizeof(class3[0]);   /* 元素个数 = 5 */

    printf("\n--- 全班成绩单 ---\n");
    printf("%-8s %-8s %s\n", "姓名", "学号", "成绩");   /* %-8s 左对齐占 8 格 */
    for (int i = 0; i < count; i++) {
        printf("%-8s %-8d %d\n", class3[i].name, class3[i].id, class3[i].score);
    }

    printf("\n班级平均分 = %.2f\n", average_score(class3, count));

    Student top = find_top(class3, count);
    printf("第一名: %s（%d 分）\n", top.name, top.score);
    /* find_top 返回整个结构体，所以可以一次拿到姓名和分数。
     * 不过结构体可能很大，复制有开销，实际项目里常返回指针或下标。 */

    /* ▶▶▶ 第 5 段：指针指向结构体 —— 用 -> 访问成员
     *  做什么：让指针 p 指向 xiaoming，用箭头取出姓名和成绩；
     *          再通过箭头把成绩改成 100；最后指向数组第一个元素再试一次。
     *  新语法：Student *p = &xiaoming;、p->name、p->score = 100
     *  预期输出：
     *      （空行）
     *      用指针访问 xiaoming：姓名 = 小明，成绩 = 88
     *      通过 p->score = 100 修改后，xiaoming.score = 100
     *      class3[0] 通过指针访问：小明
     */
    Student *p = &xiaoming;
    /* (*p).score 太啰嗦，C 提供了语法糖：p->score */
    printf("\n用指针访问 xiaoming：姓名 = %s，成绩 = %d\n", p->name, p->score);

    p->score = 100;     /* 通过指针修改 */
    printf("通过 p->score = 100 修改后，xiaoming.score = %d\n", xiaoming.score);

    /* 结构体数组的元素也可以直接用下标 + 箭头 */
    Student *first = &class3[0];
    printf("class3[0] 通过指针访问：%s\n", first->name);

    /* ▶▶▶ 第 6 段：嵌套结构体 —— 成员本身又是一整包
     *  做什么：Person 里装着姓名和一个 Date（生日），
     *          一次性初始化，然后把生日的年、月、日一层层取出来打印。
     *  新语法：嵌套初始化 {"李雷", {2008, 5, 12}}、someone.birthday.year
     *  预期输出：
     *      （空行）
     *      李雷 的生日是 2008 年 5 月 12 日
     */
    Person someone = {"李雷", {2008, 5, 12}};
    printf("\n%s 的生日是 %d 年 %d 月 %d 日\n",
           someone.name,
           someone.birthday.year,
           someone.birthday.month,
           someone.birthday.day);

    return 0;
}

/* ▶▶▶ 第 7 段：print_student 的实现 —— 传值，所以拿到的只是副本
 *  做什么：把一个 Student 的三个成员按表格样式打印出来。
 *  原理：传值：函数里拿到的是副本，改动不会影响调用者的变量，也更慢。
 *        大结构体建议写成 const Student *s 传地址（不复制、也改不了）。
 *  预期输出：
 *      姓名: 小红 学号: 1002   成绩: 95
 */
void print_student(Student s) {
    /* 传值：函数里拿到的是副本，改动不会影响调用者的变量，也更慢。
     * 大结构体建议写成 const Student *s 传地址（不复制、也改不了）。 */
    printf("姓名: %-6s 学号: %-6d 成绩: %d\n", s.name, s.id, s.score);
}

/* ▶▶▶ 第 8 段：raise_score 的实现 —— 传指针，所以能改到原件
 *  做什么：给指针指向的学生加 delta 分，但最高不超过 100。
 *  原理：收到的是地址，用 -> 访问成员；这样修改的是调用者真正的那个学生。
 *  预期输出：函数本身不打印内容，效果在第 3 段里能看到：
 *            72 分 → 82 分。
 */
void raise_score(Student *s, int delta) {
    /* 收到的是地址，用 -> 访问成员；这样修改的是调用者真正的那个学生 */
    if (s == NULL) {           /* 安全检查：万一传进来的是空指针，直接返回 */
        return;
    }
    s->score += delta;
    /* 小保护：别超过 100 */
    if (s->score > 100) {
        s->score = 100;
    }
}

/* ▶▶▶ 第 9 段：average_score 的实现 —— 求全班的平均分
 *  做什么：把所有分数加起来，再除以人数。
 *  原理：先判断人数为 0 就直接返回 0.0，避免除以 0。
 *  预期输出：函数本身不打印内容，结果在第 4 段里能看到：78.80
 */
double average_score(const Student list[], int count) {
    if (count <= 0) {
        return 0.0;
    }
    int sum = 0;
    for (int i = 0; i < count; i++) {
        sum += list[i].score;
    }
    return (double)sum / count;      /* 转成 double 再除，才不会丢掉小数 */
}

/* ▶▶▶ 第 10 段：find_top 的实现 —— 找出第一名
 *  做什么：遍历数组，记住目前见过的最高分是谁，最后把ta整个结构体返回。
 *  原理：count 为 0 时数组里一个人也没有，直接读 list[0] 会越界，
 *        所以先挡一道，返回一个空的 Student。
 *  预期输出：函数本身不打印内容，结果在第 4 段里能看到：小红（95 分）
 */
Student find_top(const Student list[], int count) {
    if (count <= 0) {                     /* 一个学生都没有，别去碰 list[0] */
        Student none = {"", 0, 0};        /* 返回一个「谁都不是」的空记录 */
        return none;
    }
    Student best = list[0];
    for (int i = 1; i < count; i++) {
        if (list[i].score > best.score) {
            best = list[i];             /* 结构体可以整体赋值 */
        }
    }
    return best;
}

