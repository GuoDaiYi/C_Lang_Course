/* ▶▶▶ 第 10 段：三个统计函数的实现
 *  做什么：把平均数、方差、标准差写成三个小函数，
 *         main 里只管调用，不用重复写循环。
 *  新语法：const double data[]、return
 *  预期输出：这一段不打印任何东西，它只是被 main 调用。
 */

/* 平均数 */
double average(const double data[], int count) {
    if (count <= 0) {
        return 0.0;
    }
    double sum = 0.0;
    for (int i = 0; i < count; i++) {
        sum += data[i];
    }
    return sum / count;
}

/* 方差：每个数离平均数的距离平方，再求平均 */
double variance(const double data[], int count, double mean) {
    if (count <= 0) {
        return 0.0;
    }
    double sum = 0.0;
    for (int i = 0; i < count; i++) {
        double diff = data[i] - mean;
        sum += diff * diff;
    }
    return sum / count;
}

/* 标准差 = 方差开根号 */
double standard_deviation(const double data[], int count, double mean) {
    return sqrt(variance(data, count, mean));
}

