/* ▶▶▶ 第 1 段：把工具箱搬进程序
 *  做什么：包含 stdio.h（输入输出）和 math.h（数学函数）两个头文件。
 *  新语法：#include <math.h>
 *  预期输出：这一段不打印任何东西，只是让后面的代码「认识」sqrt 这些名字。
 *  ★ 忘了写 math.h 会怎样：编译器报 implicit declaration of function 'sqrt'，
 *    它会「猜」sqrt 返回 int，于是 1.414 被砍成 1 —— 报错还能忍，结果全错最难忍。
 */
#include <stdio.h>
#include <math.h>     /* sqrt pow fabs floor ceil round isnan isinf */

/* ▶▶▶ 第 2 段：准备圆周率 M_PI
 *  做什么：如果系统还没给 M_PI 这个名字，我们自己定义一个 3.14159265358979323846。
 *  新语法：#ifndef / #define / #endif（条件编译）
 *  预期输出：这一段同样不打印东西，但后面算圆的周长和面积时它会参与计算。
 *  ★ M_PI 不是标准 C 的一部分，它是各平台额外提供的。
 *    有的系统（比如 Linux 上的 gcc）不给它，所以最稳的做法是：
 *    如果系统已经有就用系统的，没有就自己定义一个。
 *    少了这层保险，Linux 上直接写 M_PI 会报 'M_PI' undeclared。
 */
#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

/* ▶▶▶ 第 3 段：先给 my_sqrt 打个招呼（函数声明）
 *  做什么：告诉编译器「后面会有一个叫 my_sqrt 的函数，它收一个 double，返回一个 double」。
 *  新语法：函数声明（第 7 课）
 *  预期输出：这一段不打印任何东西。
 *  ★ 为什么要写这一行：C 是从上往下读的。main 在上面，my_sqrt 的实体在下面，
 *    main 里调用 my_sqrt 的时候编译器还没见过它，就会报「找不到函数」。
 *    先写个「声明」打个招呼就解决了。（当然，把 my_sqrt 整个搬到 main 上面也行。）
 */
double my_sqrt(double x);

int main(void) {

    /* ▶▶▶ 第 4 段：math.h 是什么，-lm 又是什么（纯说明，这一段没有代码）
     *  做什么：C 标准把「常用数学函数」单独放在 math.h 里：
     *         平方根 sqrt   幂 pow     绝对值 fabs
     *         三角函数 sin cos tan      取整 floor ceil round
     *         对数 log log10            统计 exp
     *
     *  用到里面的函数，就必须写这一行：
     *         #include <math.h>
     *
     *  忘了写会怎样？编译器会报：
     *         implicit declaration of function 'sqrt'
     *  而且它会猜 sqrt 返回 int，于是结果全错——这是新手很常见的坑。
     *
     *  再看 -lm：数学函数装在一个叫 libm 的库文件里。Linux 上链接时必须
     *  明确告诉编译器把它一起链进来：
     *         cc lessons/13_math_basics.c -o math_demo -lm
     *  少了 -lm，链接阶段会报：
     *         undefined reference to `sqrt'
     *  macOS 上不需要写 -lm（系统库已经包含了），但写上也没坏处。
     *  本项目的 Makefile 已经帮你加好了，你直接 make 就行。
     *
     *  预期输出：这一段是纯文字说明，运行时不打印任何东西。
     */

    /* ▶▶▶ 第 5 段：sqrt 求平方根
     *  做什么：算 2、9、144 的平方根，顺便演示「整数会自动转成 double」。
     *  新语法：sqrt()
     *  预期输出：
     *      --- sqrt 平方根 ---
     *      sqrt(2.0)  = 1.414214
     *      sqrt(9.0)  = 3.000000
     *      sqrt(144)  = 12.000000   <-- 整数会自动转成 double
     */
    printf("--- sqrt 平方根 ---\n");
    printf("sqrt(2.0)  = %.6f\n", sqrt(2.0));
    printf("sqrt(9.0)  = %.6f\n", sqrt(9.0));
    printf("sqrt(144)  = %.6f   <-- 整数会自动转成 double\n", sqrt(144));

    /* ▶▶▶ 第 6 段：结果用 double 接，还是用 int 接？
     *  做什么：同一个 sqrt(2.0)，分别存进 double 和 int，看差别有多大。
     *  新语法：强制类型转换 (int)，把 double 砍成整数
     *  预期输出：
     *      double ok = 1.414214
     *      int    bad = 1        <-- 1.414 被截断成了 1
     *  ★ 记住：想保留小数，变量就得是 double。int 接 double 是「截断」不是「四舍五入」。
     */
    /* 坑：sqrt 的结果必须存进 double，不能存进 int */
    double ok = sqrt(2.0);
    int bad = (int)sqrt(2.0);       /* 强制转换：小数部分被直接丢掉，不是四舍五入！ */
    printf("\ndouble ok = %.6f\n", ok);
    printf("int    bad = %d        <-- 1.414 被截断成了 1\n", bad);
    /* 记住：想保留小数，变量就得是 double。 */

    /* ▶▶▶ 第 7 段：pow 乘方
     *  做什么：算 2 的 10 次方、9 的 0.5 次方（开平方）、2 的 0 次方、5 的 -1 次方。
     *  新语法：pow(底数, 指数)
     *  预期输出：
     *      --- pow 乘方 ---
     *      pow(2.0, 10.0) = 1024.00
     *      pow(9.0, 0.5)  = 3.00   <-- 开平方，和 sqrt 一样
     *      pow(2.0, 0.0)  = 1.00   <-- 任何数的 0 次方是 1
     *      pow(5.0, -1.0) = 0.2000   <-- 负指数就是倒数
     *      pow(2, 3)      = 8.00   <-- 写成整数也能用
     *
     *  ★ pow(底数, 指数) = 底数 ^ 指数。
     *    注意参数顺序：先底数，后指数，写反了不会报错，但结果全错。
     */
    printf("\n--- pow 乘方 ---\n");
    printf("pow(2.0, 10.0) = %.2f\n", pow(2.0, 10.0));
    printf("pow(9.0, 0.5)  = %.2f   <-- 开平方，和 sqrt 一样\n", pow(9.0, 0.5));
    printf("pow(2.0, 0.0)  = %.2f   <-- 任何数的 0 次方是 1\n", pow(2.0, 0.0));
    printf("pow(5.0, -1.0) = %.4f   <-- 负指数就是倒数\n", pow(5.0, -1.0));

    /* 整数也能传给 pow，C 会自动转成 double */
    printf("pow(2, 3)      = %.2f   <-- 写成整数也能用\n", pow(2, 3));

    /* ▶▶▶ 第 8 段：fabs 浮点绝对值
     *  做什么：把负数变成正数，0 变成 0。
     *  新语法：fabs()
     *  预期输出：
     *      --- fabs 绝对值 ---
     *      fabs(-3.7) = 3.70
     *      fabs(3.7)  = 3.70
     *      fabs(0.0)  = 0.00
     *
     *  ★ fabs 专门处理 double。整数取绝对值用 abs（在 stdlib.h 里）。
     */
    printf("\n--- fabs 绝对值 ---\n");
    printf("fabs(-3.7) = %.2f\n", fabs(-3.7));
    printf("fabs(3.7)  = %.2f\n", fabs(3.7));
    printf("fabs(0.0)  = %.2f\n", fabs(0.0));

    /* ▶▶▶ 第 9 段：实战——算圆的周长和面积
     *  做什么：有了 M_PI 和 sqrt，这两个公式就能直接算了：
     *         周长 C = 2 * PI * r
     *         面积 S = PI * r * r
     *  新语法：把公式写成一行的表达式，交给 printf 打印
     *  预期输出：
     *      --- 圆的周长和面积 ---
     *      半径 2.5
     *      周长 = 15.7080
     *      面积 = 19.6350
     */
    printf("\n--- 圆的周长和面积 ---\n");
    double radius = 2.5;
    double circumference = 2.0 * M_PI * radius;
    double area = M_PI * radius * radius;
    printf("半径 %.1f\n", radius);
    printf("周长 = %.4f\n", circumference);
    printf("面积 = %.4f\n", area);

    /* ▶▶▶ 第 10 段：两个特殊的返回值——NaN 和 inf
     *  做什么：算一个「算不出来」的平方根，再算一个除以 0，看看程序给什么。
     *  新语法：isnan()、isinf()、NAN
     *  预期输出：
     *      --- NaN 和 inf ---
     *      sqrt(-1.0) = nan
     *        -> 这是一个 NaN（不是有效数字），要检查输入正负
     *      1.0 / 0.0  = inf
     *        -> 这是一个 inf（无穷大），说明分母是 0
     *
     *  ★ 浮点运算出错时不会像整数那样崩溃，而是返回一个特殊的值：
     *      NaN = Not a Number（算不出来，比如给负数开平方）
     *      inf = infinity（无穷大，比如除以 0）
     *    这两个值要专门检查，不能直接 == 比较（NaN != NaN）。
     */
    printf("\n--- NaN 和 inf ---\n");

    double bad_sqrt = sqrt(-1.0);
    printf("sqrt(-1.0) = %f\n", bad_sqrt);
    if (isnan(bad_sqrt)) {
        printf("  -> 这是一个 NaN（不是有效数字），要检查输入正负\n");
    }
    /* 注意：NaN 和自己比较也不相等，
     *   if (bad_sqrt == bad_sqrt)  永远不进这个分支
     * 所以判断 NaN 必须用 isnan()。 */

    double infinite = 1.0 / 0.0;
    printf("1.0 / 0.0  = %f\n", infinite);
    if (isinf(infinite)) {
        printf("  -> 这是一个 inf（无穷大），说明分母是 0\n");
    }
    /* 对比一下：整数除以 0 会直接让程序崩溃，
     * 浮点数除以 0 不会崩，只会得到 inf。所以写代码时
     * 除法之前还是老老实实检查一下分母。 */

    /* ▶▶▶ 第 11 段：自己写一个平方根（牛顿迭代法）
     *  做什么：库函数 sqrt 是怎么算出来的？用「牛顿迭代法」：
     *         猜一个答案 g，然后不断改进它：
     *             g = (g + x / g) / 2
     *         每算一次就逼近真实答案，几轮之后足够精确。
     *  新语法：for 循环里的循环变量（第 6 课）
     *  预期输出（两列数字完全一样，说明我的实现是对的）：
     *      --- 自己实现 sqrt（牛顿迭代法） ---
     *      sqrt(2.0): 库函数 1.4142135624 | 我的实现 1.4142135624
     *      sqrt(4.0): 库函数 2.0000000000 | 我的实现 2.0000000000
     *      sqrt(6.0): 库函数 2.4494897428 | 我的实现 2.4494897428
     *      sqrt(8.0): 库函数 2.8284271247 | 我的实现 2.8284271247
     *      sqrt(10.0): 库函数 3.1622776602 | 我的实现 3.1622776602
     *
     *  真实项目里当然还是用 sqrt：又快又准，还处理了各种边界情况。
     */
    printf("\n--- 自己实现 sqrt（牛顿迭代法） ---\n");
    for (double x = 2.0; x <= 10.0; x += 2.0) {
        printf("sqrt(%.1f): 库函数 %.10f | 我的实现 %.10f\n",
               x, sqrt(x), my_sqrt(x));
    }
    /* 两行数字一模一样，说明我的实现是对的。
     * 真实项目里当然还是用 sqrt：又快又准，还处理了各种边界情况。 */

    /* ▶▶▶ 第 12 段：动手输入一个数
     *  做什么：把上面学到的用起来——输入一个数，输出它的平方根。
     *  新语法：scanf("%lf", &变量)、if / else
     *  预期输出（输入 25 时）：
     *      --- 试一试 ---
     *      请输入一个正数，我来算它的平方根：sqrt(25.00) = 5.000000
     *  如果输入 -4，则打印：-4.00 没有平方根（负数开方得到 NaN）。
     */
    printf("\n--- 试一试 ---\n");
    printf("请输入一个正数，我来算它的平方根：");

    double input = 0.0;
    if (scanf("%lf", &input) != 1) {
        printf("没读到数字，程序结束。\n");
        return 1;
    }

    if (input < 0.0) {
        printf("%.2f 没有平方根（负数开方得到 NaN）。\n", input);
    } else {
        printf("sqrt(%.2f) = %.6f\n", input, sqrt(input));
    }

    return 0;
}

/* ============================================================
 * 牛顿迭代法实现平方根（第 7 课：函数要写在 main 前面，
 * 或者先写个声明「打个招呼」）
 * ============================================================ */
double my_sqrt(double x) {
    if (x < 0.0) {
        return NAN;          /* 负数没有平方根，返回 NaN */
    }
    if (x == 0.0) {
        return 0.0;
    }

    /* 迭代次数：每一轮都让猜测更准一点，20 轮已经足够精确 */
    const int iterations = 20;

    double guess = x / 2.0;     /* 第一个猜测值 */
    for (int i = 0; i < iterations; i++) {
        guess = 0.5 * (guess + x / guess);   /* 每轮把猜测改得更准一点 */
    }
    return guess;
}

