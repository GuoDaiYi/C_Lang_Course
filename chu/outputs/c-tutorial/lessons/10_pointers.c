/*
 * ============================================================================
 *  第 10 课：指针（C 语言的灵魂，也是新手的最大关卡）
 * ============================================================================
 *
 *  本课知识点：内存地址、取地址 &、解引用 *、通过指针改变量、
 *              指针与数组、指针运算、NULL、交换两个数的经典例子
 *
 *  ▶ 这节课要解决什么问题
 *  ---------------------------------------------------------------------------
 *    先做一个比喻：把电脑内存想成一排编号的储物柜，每个柜子都有门牌号。
 *
 *      · 你写 int n = 42;  相当于在某个柜子里放进一个 42；
 *      · 变量名 n 就是贴在柜子上的便利贴，你不用记门牌号也能拿到 42；
 *      · 指针，就是「另一张便利贴，上面写的不是 42，而是门牌号」。
 *
 *    一句话概括：C 里的指针，就是「存地址的变量」。
 *      普通变量装的是数据，指针装的是「数据住在哪」。
 *      &  →  拿到地址；
 *      *  →  根据地址去拿数据 / 放数据。
 *
 *    学指针 = 学「怎么拿到门牌号、怎么顺着门牌号找到东西、
 *    怎么把新东西放进那个柜子」。这是 C 语言里最强大、也最容易出事的部分。
 *
 *    学完这一课你能做到：
 *      1) 打印任意变量的内存地址，并解释这个地址代表什么；
 *      2) 写出让函数真正修改外部变量的 swap（交换两个数的值）；
 *      3) 用指针遍历数组，知道数组名为什么能直接当地址用；
 *      4) 知道 NULL 是什么，以及什么时候会把程序搞崩溃。
 *
 *  ▶ 学这节课之前，你需要已经会（前置知识）
 *  ---------------------------------------------------------------------------
 *    ✅ 已经会：第 2 课：变量与数据类型（会声明 int / double / char 变量）
 *    ✅ 已经会：第 7 课：函数（会写函数、会传参数、知道参数能写成指针类型）
 *    ✅ 已经会：第 8 课：数组（会用下标 arr[0]、知道 sizeof 能算数组占多少字节）
 *    ✅ 已经会：第 9 课：字符串（知道 char * 其实就是「指向字符的指针」）
 *    🔁 忘了就看：第 7 课里「C 的参数是值传递：函数里改参数不会影响外面的变量」
 *    🔁 忘了就看：第 8 课里「数组名在多数场合会自动变成第一个元素的地址」
 *    🔁 忘了就看：第 8 课里「sizeof(arr) 在 main 里是整个数组，在函数里只算一个元素」
 *    ❓ 开课自测（4 题，能答上来再往下学；答案在文件最末尾）
 *       1) 变量 a 的地址该怎么写出来？取地址用哪个符号？
 *       2) 函数里改了形参的值，调用者的变量会跟着变吗？为什么？
 *       3) int *p 这行代码应该怎么念？p 到底是什么？
 *       4) NULL 是什么意思？对 NULL 指针解引用会发生什么？
 *
 *  ▶ 本节课新出现的语法（先扫一眼这张表，看不懂的先跳过，学到自然会懂）
 *  ---------------------------------------------------------------------------
 *    1) &变量
 *       读作：取……的地址
 *       作用：拿到一个变量的「门牌号」。&n 就是 n 住的那间柜子的编号。
 *       注意：& 写在变量左边是「取地址」，写在声明里是「这是一个指针」，
 *             同一个符号两种用法，靠它出现的位置区分。
 *
 *    2) int *p;  /  int *p = &n;
 *       读作：p 是一个（指向 int 的）指针
 *       作用：声明一个专门用来装地址的变量，再把 n 的地址交给它。
 *       注意：星号写在类型旁边还是变量旁边都一样（int *p 和 int* p 等价），
 *             但一条声明里只能有一个星号——int *p, q; 里的 q 是普通 int，不是指针！
 *
 *    3) *p（解引用）
 *       读作：p 指向的那个值
 *       作用：顺着地址找到那个变量，把里面的内容取出来，或者写进去。
 *       注意：这里的 * 和声明里的 * 完全不是一回事。
 *             int *p = &n; 里的 * 是「声明指针」；
 *             *p = 100;     里的 * 是「解引用，去改那个变量」。
 *
 *    4) NULL
 *       读作：空指针 / 空
 *       作用：一个特殊值，表示「这个指针什么都不指向」。它来自 <stdio.h>
 *             （也可以来自 <stddef.h>）。
 *       注意：对 NULL 指针解引用会让程序直接崩溃（段错误），
 *             所以规矩是：用指针之前先 if (p != NULL) 检查一下。
 *
 *    5) %p
 *       读作：按指针地址打印
 *       作用：printf 里专门用来打印地址的格式符。
 *       注意：%p 期望的参数类型是「通用指针」void *，
 *             所以标准写法是 printf("%p\n", (void *)&n);。
 *
 *    6) (void *) 强制类型转换
 *       读作：转成通用指针
 *       作用：把 int * / char * 统一变成「不带类型的地址」，好交给 %p。
 *       注意：它只改变「怎么看待这个地址」，不会改变地址本身，
 *             更不会改变里面的数据。printf("%p\n", (void *)&n); 里的
 *             (void *) 就是干这个的——把具体类型的指针，统一成
 *             「通用地址」，%p 才肯好好收下它。
 *
 *    7) 指针运算 q + 2、*(q + 2)、q[2]
 *       读作：q 加 2 / q 指向的元素往后数第 2 个
 *       作用：在数组里移动位置。这三种写法完全等价。
 *       注意：q + 2 不是「门牌号 + 2」，而是「往后移动 2 个 int 的位置」，
 *             真实地址会加上 2 * sizeof(int) 个字节。
 *
 *    8) 指针相减 third - first
 *       读作：third 减去 first
 *       作用：算出两个指针之间隔了多少个元素（不是差了多少个字节）。
 *       注意：结果类型是 long 而不是 int，所以打印要用 %ld，
 *             本文件里写成了 (long)(third - first)。
 *
 *    9) const int data[]
 *       读作：常量整型数组
 *       作用：告诉编译器「这个函数只读这个数组，不会改它」。
 *       注意：const 是给「指针指向的东西」加锁，不是给指针本身加锁。
 *             const int *p 可以改 p（让它指向别处），但不许改 *p。
 *
 *    10) void swap(int *pa, int *pb);
 *       读作：函数 swap，参数是指针
 *       作用：提前告诉编译器「有这个函数，它的参数是指针」。
 *       注意：写指针参数时 & 和 * 一个都不能少——
 *             声明写 int *pa，调用时就要传 &x 这样的地址。
 *
 *    11) const int count = 4;
 *       读作：常量 count 等于 4
 *       作用：给「4」起个名字。数组长度、循环次数、传参个数都用它，
 *             以后想改长度，只改这一处就行。
 *       注意：名字要能自己说明意思。写 arr[4] 别人不知道 4 是什么，
 *             写 arr[COUNT] 一眼就懂。
 *
 *  ▶ 怎么读这个文件
 *  ---------------------------------------------------------------------------
 *    1. 先读完上面这三块（问题 / 前置 / 新语法），心里先有个框架；
 *    2. 往下看代码，每段代码前面都有「▶▶▶ 第 N 段」，讲清这段在干嘛、
 *       跑起来会看到什么；
 *    3. 边看边在脑子里预演输出，觉得「我大概知道这段会打印什么」再往下走；
 *    4. 最后做「动手练习」和「自测题」。
 *
 *  运行方式（在本项目根目录下）：
 *    make run L=lessons/10_pointers
 *    或者手动：cc lessons/10_pointers.c -o demo && ./demo
 * ============================================================================ */

#include <stdio.h>

/* 我们用指针来写一个函数：交换调用者那边的两个变量 */
void swap(int *pa, int *pb);

/* 用输出参数一次算出最大值和最小值 */
void min_max(const int data[], int count, int *out_min, int *out_max);

int main(void) {

    /* ▶▶▶ 第 1 段：地址 —— 变量住在内存里的门牌号
     *  做什么：创建一个整数变量 n，然后同时打印它的「值」和它的「地址」。
     *  新语法：&（取地址运算符）、%p（打印地址的格式符）、
     *          (void *)（转成通用指针，配合 %p 用）
     *  预期输出：
     *      n 的值 = 42
     *      n 的地址 = 0x7ff7bc5ff0c8
     *    （地址的具体数字每次运行都不一样，这很正常；
     *      只要是 0x 开头的一串十六进制就说明拿对了）
     */
    int n = 42;
    printf("n 的值 = %d\n", n);
    printf("n 的地址 = %p\n", (void *)&n);
    /* &n 读作「n 的地址」，取值是 0x... 形式的十六进制门牌号。
     * 每次运行看到的具体数字可能不一样，这很正常。 */

    /* ▶▶▶ 第 2 段：指针变量 —— 专门用来装地址的盒子
     *  做什么：声明一个指针 p，把 n 的地址存进去；
     *          再把「p 里存的地址」和「顺着这个地址找到的值」分别打印出来。
     *  新语法：int *p = &n;（声明指针并初始化）、(void *)p
     *  预期输出：
     *      （上面留一个空行，因为格式串开头有 \n）
     *      p 里存的地址 = 0x7ff7bc5ff0c8    ← 和第 1 段里 n 的地址一模一样
     *      *p 取出的值  = 42   <-- *p 就是「顺着地址找到的内容」
     */
    int *p = &n;
    /* 读法：int *p 表示「p 是一个指针，它指向一个 int」。
     * 赋值时把 n 的地址交给它。 */

    printf("\np 里存的地址 = %p\n", (void *)p);
    printf("*p 取出的值  = %d   <-- *p 就是「顺着地址找到的内容」\n", *p);

    /* ▶▶▶ 第 3 段：通过指针修改原变量
     *  做什么：这次没有直接写 n = 100，而是顺着 p 里存的地址，
     *          把那个位置的数字改成 100，然后再打印 n。
     *  新语法：*p = 100（解引用 + 赋值）
     *  预期输出：
     *      （空行）
     *      执行 *p = 100; 之后，n = 100
     *    关键点：代码里一个字母 n = 都没出现，但 n 的值真的变了。
     */
    *p = 100;       /* 顺着地址把新值写进去 */
    printf("\n执行 *p = 100; 之后，n = %d\n", n);
    /* 注意：我们没有直接写 n = 100，但 n 真的变了。
     * 因为 p 和 n 指的是同一块内存。 */

    /* ▶▶▶ 第 4 段：一个变量可以有好几个指针指着它
     *  做什么：再声明一个指针 another，它也指向 n；
     *          通过 another 把 n 改成 7，然后同时打印 n 和 *p。
     *  新语法：int *another = &n;（多个指针可以指向同一个变量）
     *  预期输出：
     *      通过另一个指针改成 7 之后，n = 7，*p 也变成 7
     *    关键点：n 和 *p 永远是一致的，因为它们看的是同一块内存。
     */
    int *another = &n;      /* another 也指向 n */
    *another = 7;
    printf("通过另一个指针改成 7 之后，n = %d，*p 也变成 %d\n", n, *p);

    /* ▶▶▶ 第 5 段：经典例子 —— 用指针写 swap，交换两个变量的值
     *  做什么：先打印 x 和 y，调用 swap(&x, &y) 交换它们，再打印一次。
     *  为什么必须用指针？因为 C 是值传递：函数拿到的参数是调用者变量的副本。
     *          函数里改副本，调用者的原变量一点都不会变。
     *          只有把「地址」交给函数，函数才能改到真的那个变量。
     *  新语法：&x（把地址传给函数）、调用写成 swap(&x, &y);
     *  预期输出：
     *      （空行）
     *      交换前: x = 1, y = 2
     *      交换后: x = 2, y = 1
     */
    int x = 1;
    int y = 2;
    printf("\n交换前: x = %d, y = %d\n", x, y);
    swap(&x, &y);                       /* 传的是地址，所以加 & */
    printf("交换后: x = %d, y = %d\n", x, y);

    /* ▶▶▶ 第 6 段：指针和数组其实是一家人
     *  做什么：创建一个 4 个元素的数组，让指针 q 指向它；
     *          分别用「下标写法」和「指针写法」取同一个数，证明它们完全等价；
     *          最后用指针把整个数组从头到尾走一遍，并算出两个元素的间隔。
     *  新语法：int *q = arr（数组名自动变成首元素地址）、
     *          *(arr + i)、指针相减 third - first
     *  预期输出：
     *      （空行）
     *      --- 指针与数组 ---
     *      arr[0] = 10，*q = 10（完全等价）
     *      arr[2] = 30，*(q + 2) = 30（也是等价的）
     *      用指针遍历: 10 20 30 40
     *      &arr[2] - &arr[0] = 2（相隔 2 个元素）
     */
    const int count = 4;        /* 元素个数，起个名字，后面几处都要用 */
    int arr[count] = {10, 20, 30, 40};
    int *q = arr;    /* 数组名在多数场合会自动变成「第一个元素的地址」 */

    printf("\n--- 指针与数组 ---\n");
    printf("arr[0] = %d，*q = %d（完全等价）\n", arr[0], *q);
    printf("arr[2] = %d，*(q + 2) = %d（也是等价的）\n", arr[2], *(q + 2));
    /* q + 2 不是「地址加 2」，而是「往后移动 2 个 int」，
     * 实际地址增加 2 * sizeof(int) = 8 字节。这叫指针运算。 */

    /* 用指针遍历数组 */
    printf("用指针遍历: ");
    for (int i = 0; i < count; i++) {
        printf("%d ", *(arr + i));      /* 也可以写成 q[i] */
    }
    printf("\n");

    /* 指针相减 = 相隔多少个元素 */
    int *first = &arr[0];
    int *third = &arr[2];
    printf("&arr[2] - &arr[0] = %ld（相隔 2 个元素）\n", (long)(third - first));

    /* ▶▶▶ 第 7 段：把数组传进函数 —— 其实传的是指针
     *  做什么：先打印 main 里 sizeof(arr) 的结果（整个数组占多少字节），
     *          再把数组和两个空变量交给 min_max，
     *          让它用两个指针把最大值、最小值写回这两个变量。
     *  新语法：min_max(arr, count, &min, &max)（输出参数：结果用指针带回来）
     *  预期输出：
     *      （空行）
     *      在 main 里 sizeof(arr) = 16（整个数组）    ← 4 个 int，每个 4 字节
     *      min_max 算出的最大值 = 40，最小值 = 10
     */
    /* 这就是第 8 课说「函数里 sizeof 算不出数组长度」的原因： */

    printf("\n在 main 里 sizeof(arr) = %zu（整个数组）\n", sizeof(arr));

    int min = 0;
    int max = 0;
    min_max(arr, count, &min, &max);        /* 用两个指针把结果带回来 */
    printf("min_max 算出的最大值 = %d，最小值 = %d\n", max, min);

    /* ▶▶▶ 第 8 段：NULL —— 明确表示「我什么都不指向」
     *  做什么：把一个指针设成 NULL，先判断它是不是空；
     *          再回头检查 p 是不是有效的，安全地访问它。
     *  新语法：NULL 宏、if (p != NULL)
     *  预期输出：
     *      （空行）
     *      empty 是空指针，现在还不能解引用 *empty（会崩溃）
     *      *p 可以安全访问，值是 7
     *  为什么重要：printf("%d", *empty) 这样的写法会让程序当场崩掉，
     *              所以「先判断，再用」是铁律。
     */
    int *empty = NULL;
    if (empty == NULL) {
        printf("\nempty 是空指针，现在还不能解引用 *empty（会崩溃）\n");
    }

    /* 使用任何指针前都应该先确认它有效 */
    if (p != NULL) {
        printf("*p 可以安全访问，值是 %d\n", *p);
    }

    return 0;
}

/* ▶▶▶ 第 9 段：swap 函数的实现 —— 真正把两个数的值对调
 *  做什么：把 pa 指向的值和 pb 指向的值交换。
 *  原理：pa、pb 是指针，指向调用者那边的 x 和 y。
 *        要交换的是「它们指向的值」，所以要用 *。
 *  预期输出：函数本身不打印任何东西，效果在第 5 段里已经看到：
 *            交换前 x = 1, y = 2 → 交换后 x = 2, y = 1
 */
void swap(int *pa, int *pb) {
    /* pa、pb 是指针，指向调用者那边的 x 和 y。
     * 要交换的是「它们指向的值」，所以要用 *。 */
    int temp = *pa;      /* 备份 a 指向的值 */
    *pa = *pb;           /* 把 b 的值写到 a 那边 */
    *pb = temp;          /* 把备份写到 b 那边 */

    /* 如果写成 pa = pb; 那只是让两个指针对指同一个地方，
     * 调用者的变量完全没变 —— 这是初学者最常见的错误。 */
}

/* ▶▶▶ 第 10 段：min_max 函数的实现 —— 用「输出参数」一次带回两个结果
 *  做什么：遍历整个数组，找出最小值和最大值，
 *         再通过 out_min / out_max 两个指针写回调用者的变量。
 *  原理：out_min、out_max 叫「输出参数」——
 *        函数只能 return 一个值，想返回多个结果时就用指针从门口递出去。
 *  预期输出：函数本身不打印内容，结果在第 7 段里能看到：
 *            最大值 = 40，最小值 = 10
 */
void min_max(const int data[], int count, int *out_min, int *out_max) {
    /* out_min、out_max 叫「输出参数」：
     * 函数只能 return 一个值，想返回多个结果时就用指针从门口递出去。 */
    if (count <= 0) {
        return;                 /* 保险起见，直接返回 */
    }

    int lo = data[0];
    int hi = data[0];
    for (int i = 1; i < count; i++) {
        if (data[i] < lo) {
            lo = data[i];
        }
        if (data[i] > hi) {
            hi = data[i];
        }
    }

    *out_min = lo;      /* 写回调用者的变量 */
    *out_max = hi;
}

