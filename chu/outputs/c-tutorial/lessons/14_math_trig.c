/* ▶▶▶ 第 13 段：三个工具函数的实现
 *  做什么：把「角度 ↔ 弧度」的换算和「角度整理到 0~360」写成三个小函数。
 *  新语法：return 语句把结果交回给调用者
 *  预期输出：这一段不打印任何东西，它只是被 main 调用。
 */

/* 角度转弧度 */
double deg_to_rad(double degree) {
    return degree * M_PI / 180.0;
}

/* 弧度转角度 */
double rad_to_deg(double radian) {
    return radian * 180.0 / M_PI;
}

/* 把角度整理到 0 ~ 360 度之间 */
double normalize_angle(double degree) {
    double result = fmod(degree, 360.0);   /* fmod 是浮点数取余 */
    if (result < 0.0) {
        result += 360.0;
    }
    return result;
}

