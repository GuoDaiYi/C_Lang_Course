/*
 * ============================================================================
 *  练习 4 参考答案：菜单式计算器
 * ============================================================================
 *
 *  ▶ 这个练习要练什么
 *  ---------------------------------------------------------------------------
 *    一个能反复用的小程序：显示菜单 → 读用户的选择 → 按选择执行不同的功能
 *    → 再显示菜单，直到用户选 0 才退出。
 *    对应第 5 课（switch）、第 6 课（while 循环），
 *    另外用到了第 3 课（输入）、第 4 课（条件判断）和第 7 课（函数）。
 *
 *    这道题真正的难点不是 switch 本身，
 *    而是「循环 + switch + 输入校验」三者怎么配合。
 *
 *  ▶ 前置知识（开始前先自测）
 *  ---------------------------------------------------------------------------
 *    ✅ 已经会：第 5 课：多分支选择 switch（case、break、default、多个 case 共用）
 *    ✅ 已经会：第 6 课：循环（while、break、continue）
 *    ✅ 已经会：第 3 课：让程序会问问题（scanf 的返回值、EOF）
 *    ✅ 已经会：第 4 课：条件判断（if / else、&& 和 ||）
 *    ✅ 已经会：第 7 课：函数（函数原型、参数、返回值）
 *    🔁 忘了就看：第 5 课第 2 节「switch 的基本写法」、第 5 课第 3 节「break：漏掉会发生什么」
 *    🔁 忘了就看：第 5 课第 4 节「多个 case 共用一段代码」、第 5 课第 5 节「default：兜底分支」
 *    🔁 忘了就看：第 6 课第 3 节「while 循环」、第 6 课第 5 节「break 和 continue」
 *    ❓ 自测（答案在文件末尾）
 *       1) switch 里的 case 忘了写 break，会发生什么？
 *       2) while (1) 这个循环怎么才能停下来？
 *       3) scanf("%d", &x) 返回 0 表示什么？返回 EOF 又表示什么？
 *
 *  ▶ 题目要求（做完练习再看）
 *  ---------------------------------------------------------------------------
 *    一直显示这个菜单，直到用户选 0 才结束：
 *        1. 加法   2. 减法   3. 乘法   4. 除法   0. 退出
 *    选 1~4 时先读两个数再输出结果；除法要检查除数是不是 0；
 *    输入不是数字时提示后重新来。
 *
 *    验收样例（这是真的跑出来的输出，可以直接和你的程序对照）：
 *      输入 1  然后回车
 *      输入 10  然后回车
 *      输入 4  然后回车
 *      输入 0  然后回车
 *
 *      --------- 计算器 ---------
 *        1. 加法
 *        2. 减法
 *        3. 乘法
 *        4. 除法
 *        0. 退出
 *      --------------------------
 *      请选择：
 *      第一个数：
 *      第二个数：
 *      10.00 + 4.00 = 14.00
 *      --------------------------
 *
 *      --------- 计算器 ---------
 *        1. 加法
 *        2. 减法
 *        3. 乘法
 *        4. 除法
 *        0. 退出
 *      --------------------------
 *      请选择：
 *
 *      再见！这次一共做了 1 次计算。
 *
 *  ▶ 需要用到的语法（速查）
 *  ---------------------------------------------------------------------------
 *    1) while (1) 死循环
 *       写法：while (1) { ... }
 *       作用：条件永远是「真」，所以循环体可以一直跑。
 *              想停下来就靠循环体里的 break 或者 return。
 *       坑：一定要有一条能走到的退出路径，不然程序永远停不下来。
 *
 *    2) switch / case / break
 *       写法：switch (choice) { case 1: ... break; default: ... }
 *       作用：choice 等于哪个 case，就从哪一段开始执行。
 *       坑：★ 漏掉 break 会「掉」进下一个 case 继续执行，
 *            这是 switch 最常见的 bug。
 *
 *    3) 多个 case 共用一段代码
 *       写法：case 1: case 2: case 3: { ... break; }
 *       作用：这几个选项做同样的事，就写在一起，中间不写 break。
 *       坑：只有最后那个 break 是真的 break。
 *
 *    4) continue
 *       写法：continue;
 *       作用：立刻结束这一轮循环，回到循环开头重新判断条件。
 *              「输入不对，重新来一次」就靠它。
 *       坑：continue 和 break 别搞混：
 *            break 跳出循环，continue 只是跳过这一轮。
 *
 *    5) scanf 的返回值
 *       写法：int rc = scanf("%d", &x);
 *       作用：rc 等于成功读到的个数。读到 1 个是成功；
 *              读到 0 个说明用户敲的不是数字；
 *              EOF（-1）说明输入已经结束了。
 *       坑：不等价于 1 的时候一定要处理，不然程序会用垃圾数据继续算。
 *
 *  ▶ 解法思路（先看思路，再看代码）
 *  ---------------------------------------------------------------------------
 *    1) 先把程序的「骨架」搭出来：一个 while (1) 包住整个菜单流程，
 *       循环体里四件事 —— 打印菜单、读选择、switch 分发、打印分隔线。
 *       循环怎么停？选 0 时 return 0 直接结束程序。
 *
 *    2) 再处理「读选择」这一小段，注意三种情况：
 *       读到 0（不是数字）→ 提示一下，continue 回到菜单重新来；
 *       读到 EOF（输入结束）→ 打印「输入已结束」然后退出程序；
 *       读到 1（成功）→ 把 last_int 里的数存进 choice，继续往下走。
 *
 *    3) switch 分发的时候发现：case 1~4 做的事情其实一模一样，
 *       都是「读两个数、算一下、打印结果」，只有运算本身不同。
 *       所以第一层 switch 把 case 1~4 合并成一段，
 *       在这一段里再用一个第二层 switch 决定做加还是减还是乘还是除。
 *       这样做的好处：读两个数和查除数的那几行只写了一遍，不会漏。
 *
 *    4) 除数检查要放在「除之前」：
 *       if (choice == 4 && b == 0.0) 就提示「除数不能为 0」然后跳过这次计算。
 *       放在除完之后就晚了，0 除数在 C 里是「除以零」，行为不可预期。
 *
 *    5) 读两个数的失败处理要写两遍（第一个数、第二个数），
 *       每一处都要先判断返回值，不成功就提示「输入无效」并跳过这次计算。
 *       漏掉判断的话，程序会拿着上一次留下的旧数字继续算，结果莫名其妙。
 *
 *    提醒：这题最容易被写错的地方有三个。
 *          一是 switch 里漏 break，选 1 却算出了减法的结果；
 *          二是输入 abc 之后没清输入行，程序会一直说「输入无效」；
 *          三是除数为 0 没检查。
 *
 *  ▶ 代码怎么读
 *  ---------------------------------------------------------------------------
 *    下面每段代码前面都有「▶▶▶ 第 N 段」，讲清这段在干嘛、跑起来会看到什么。
 *    建议顺序：先扫一眼每段的小标题 → 读代码 → 在脑子里预演输出 →
 *      最后把文件关掉，凭记忆重新写一遍，这样才真的学会。
 *
 *    第 1 段：函数声明（原型）。
 *    第 2 段：main 里的 while (1) 循环 —— 每轮做四件事。
 *    第 3 段：读用户的选择，并处理三种情况。
 *    第 4 段：第一层 switch —— 把 case 1~4 合并，分发到「读两个数再算」。
 *    第 5 段：读第一个数。
 *    第 6 段：读第二个数。
 *    第 7 段：除法检查除数是不是 0。
 *    第 8 段：第二层 switch —— 决定做加、减、乘还是除。
 *    第 9 段：打印结果，计数加一。
 *    第 10 段：case 0（退出）和 default（没有这个选项）。
 *    第 11 段：每轮结束打印分隔线。
 *    第 12 段往后：各个辅助函数（打印菜单、读数、清输入行、四则运算）。
 *
 *  运行方式（在本项目根目录下）：
 *    make run L=exercises/solutions/ex04_switch
 *    参考答案在 exercises/solutions/ex04_switch.c
 * ============================================================================
 */

#include <stdio.h>

/* ▶▶▶ 第 1 段：函数声明（原型）
 *  做什么：告诉编译器「下面这些函数存在，叫什么名字、收什么参数、返回什么」。
 *          因为它们的定义写在 main 后面，所以必须先声明。
 */
void print_menu(void);
int  read_int(void);
int  read_number(void);
void clear_rest_of_line(void);

double add(double a, double b);
double sub(double a, double b);
double mul(double a, double b);
double divide(double a, double b);

/* ▶▶▶ 第 2 段：全局变量 —— 最近一次读到的数
 *  为什么要有它：read_int / read_number 这两个函数要同时告诉你两件事 ——
 *  「读到的数是多少」和「读成功了没有」。C 的函数只能直接返回一样东西，
 *  所以用返回值表示成功没有，用这两个全局变量装读到的数。
 *  （另一种写法是用指针参数，但那是第 10 课的内容，这里先不碰。）
 *  注意：它们必须写在 main 前面，因为 main 里也要用到它们。
 */
int    last_int    = 0;
double last_number = 0.0;

int main(void) {
    /* ▶▶▶ 第 3 段：main 里的 while (1) 循环
     *  做什么：整个菜单流程都在这个循环里，一直转，直到用户选 0。
     *  预期输出：一上来先打印一份菜单。
     */
    int count = 0;      /* 一共做了多少次计算 */

    while (1) {
        print_menu();

        /* ▶▶▶ 第 4 段：读用户的选择
         *  做什么：read_int() 把读到的数放进全局变量 last_int，
         *          它自己返回「读成功了没有」。
         *  三种情况：
         *    返回 -2 → 输入已经结束（比如按了 Ctrl+D），程序退出；
         *    返回 -1 → 用户敲的不是数字，提示后 continue，回到菜单重来；
         *    返回  0 → 读成功，把 last_int 存进 choice。
         *  预期输出（输入 abc 时）：输入的不是数字，请重新输入。
         */
        int choice = 0;
        printf("请选择：");
        int rc = read_int();
        if (rc == -2) {
            printf("\n输入已结束，程序退出。\n");
            return 0;
        }
        if (rc != 0) {
            printf("\n输入的不是数字，请重新输入。\n");
            continue;
        }
        choice = last_int;

        /* ▶▶▶ 第 5 段：第一层 switch —— 把 case 1~4 合并
         *  做什么：加、减、乘、除的流程完全一样（都是读两个数再算一下），
         *          所以写在一起，具体做哪种运算交给里面的第二层 switch 决定。
         *  为什么能这么写：case 1 后面没有 break，会「掉」到 case 2、
         *          case 3、case 4，效果就是「这四个选项走同一段代码」。
         */
        switch (choice) {
            case 1:
            case 2:
            case 3:
            case 4: {
                double a = 0.0;
                double b = 0.0;

                /* ▶▶▶ 第 6 段：读第一个数
                 *  做什么：先打印提示，再让 read_number() 去读。
                 *          读到的数在全局变量 last_number 里。
                 *  预期输出：第一个数：
                 */
                printf("第一个数：");
                if (read_number() != 0) {
                    printf("输入无效，这次计算跳过。\n");
                    break;
                }
                a = last_number;

                /* ▶▶▶ 第 7 段：读第二个数
                 *  做法和第一个数一模一样，只是提示语不同。
                 *  预期输出：第二个数：
                 */
                printf("第二个数：");
                if (read_number() != 0) {
                    printf("输入无效，这次计算跳过。\n");
                    break;
                }
                b = last_number;

                /* ▶▶▶ 第 8 段：除法先查除数
                 *  做什么：如果选的是除法（choice == 4）而且第二个数是 0，
                 *          就提示「除数不能为 0」并跳过这次计算。
                 *  为什么要先查：除以 0 在 C 里是「除零」，结果不可预期，
                 *          所以必须在除之前拦住。
                 *  预期输出：除数不能为 0
                 */
                if (choice == 4 && b == 0.0) {
                    printf("除数不能为 0\n");
                    break;
                }

                char op = '+';
                double result = 0.0;

                /* ▶▶▶ 第 9 段：第二层 switch —— 决定做哪一种运算
                 *  做什么：op 记下运算符，result 记下算出来的结果。
                 *  注意：走到 default 时，一定是 choice == 4（因为
                 *        上面 1~4 已经合并了），所以 default 就是除法。
                 */
                switch (choice) {
                    case 1:
                        op = '+';
                        result = add(a, b);
                        break;
                    case 2:
                        op = '-';
                        result = sub(a, b);
                        break;
                    case 3:
                        op = '*';
                        result = mul(a, b);
                        break;
                    default:                /* 一定是 case 4：除法 */
                        op = '/';
                        result = divide(a, b);
                        break;
                }

                /* ▶▶▶ 第 10 段：打印结果，计数加一
                 *  做什么：%.2f 保留 2 位小数，%c 打印那个运算符。
                 *  预期输出（10 + 4）：10.00 + 4.00 = 14.00
                 */
                printf("%.2f %c %.2f = %.2f\n", a, op, b, result);
                count++;
                break;
            }
            /* ▶▶▶ 第 11 段：case 0（退出）和 default（没有这个选项）
             *  做什么：选 0 就打印一共做了多少次计算，然后 return 结束程序；
             *          选了 1~5 以外的东西就提示一下，回到菜单重来。
             *  预期输出（选 0 时）：
             *            再见！这次一共做了 1 次计算。
             */
            case 0:
                printf("\n再见！这次一共做了 %d 次计算。\n", count);
                return 0;      /* 直接退出程序，等价于 break 跳出循环 */
            default:
                printf("没有这个选项，请输入 0-4。\n");
                break;
        }

        /* ▶▶▶ 第 12 段：每轮结束打印一行分隔线
         *  做什么：让屏幕上的内容分成一段一段的，好看也好读。
         */
        printf("--------------------------\n");
    }
}

/* ▶▶▶ 第 13 段：全局变量说明
 *  last_int 和 last_number 已经写在 main 前面了（见第 1 段之二），
 *  这里是提醒你一下它们是干什么用的。 */

/* ▶▶▶ 第 14 段：打印菜单
 *  做什么：把五行选项打出来。开头那个 \n 让菜单和上面的内容隔开一点。
 */
void print_menu(void) {
    printf("\n--------- 计算器 ---------\n");
    printf("  1. 加法\n");
    printf("  2. 减法\n");
    printf("  3. 乘法\n");
    printf("  4. 除法\n");
    printf("  0. 退出\n");
    printf("--------------------------\n");
}

/* ▶▶▶ 第 15 段：读一个整数
 *  做什么：scanf("%d", &last_int) 去读，读到的数放在全局变量 last_int 里。
 *          函数自己的返回值告诉你「读成功了没有」：
 *            返回  0 -> 读成功
 *            返回 -1 -> 输入的不是数字
 *            返回 -2 -> 输入已经结束（Ctrl+D 或输入重定向用完了）
 *  为什么要调 clear_rest_of_line()：读失败的时候（比如用户敲了 abc），
 *          那三个字符还留在输入缓冲区里，不清掉的话下一次 scanf
 *          又会读到它们，程序就会一直说「输入无效」。
 *  为什么要 printf("\n")：读完了就换一行，免得下面的提示和这行挤在一起。
 */
int read_int(void) {
    int rc = scanf("%d", &last_int);

    if (rc == EOF) {
        printf("\n");
        return -2;
    }
    clear_rest_of_line();
    if (rc != 1) {
        return -1;
    }
    printf("\n");     /* 读完了，换一行，免得下面的提示挤在一起 */
    return 0;
}

/* ▶▶▶ 第 16 段：读一个小数
 *  做法和 read_int 一样，只是格式符从 %d 换成 %lf，
 *  读到的数放在 last_number 里。
 */
int read_number(void) {
    int rc = scanf("%lf", &last_number);

    if (rc == EOF) {
        printf("\n");
        return -2;
    }
    clear_rest_of_line();
    if (rc != 1) {
        return -1;
    }
    printf("\n");
    return 0;
}

/* ▶▶▶ 第 17 段：把输入行里剩下的字符全部读掉
 *  做什么：getchar() 一次读一个字符，直到读到换行符或者输入结束。
 *  为什么需要它：见上面 read_int 里的说明。
 */
void clear_rest_of_line(void) {
    int c;
    while ((c = getchar()) != '\n' && c != EOF) {
    }
}

/* ▶▶▶ 第 18 段：四则运算
 *  做什么：四个一模一样的壳，各自做一件事：把两个数算一下返回。
 *  为什么要单独写成函数：main 里就只剩「读数 → 调用 → 打印」，
 *  一眼就看得懂在算什么。
 */
double add(double a, double b) {
    return a + b;
}

double sub(double a, double b) {
    return a - b;
}

double mul(double a, double b) {
    return a * b;
}

double divide(double a, double b) {
    return a / b;
}

/* ============================================================================
 *  ▶ 常见报错速查
 *  ---------------------------------------------------------------------------
 *  error: implicit declaration of function 'read_int'
 *      → 忘了写函数声明（TODO 1）。或者声明和定义的写法不一样。
 *
 *  warning: unused variable 'count'
 *      → 声明了 count 却没用它。要么用它做计数，要么删掉。
 *
 *  菜单转个没完 / 程序卡死
 *      → while 循环里没有能走到的退出路径。
 *        检查一下：选 0 的时候是不是真的 return 或者 break 出去了？
 *
 *  选 1 却算出了减法的结果
 *      → switch 里漏了 break，程序「掉」进了下一个 case。
 *        这就是第 5 课专门讲过的那个坑。
 *
 *  输入 abc 之后程序一直说「输入无效」
 *      → 输入行里的 abc 还在缓冲区里，下一次 scanf 又读到它。
 *        读失败后一定要调 clear_rest_of_line() 把这行剩下的字符清掉。
 *
 *  ▶ 自测答案
 *  ---------------------------------------------------------------------------
 *  1) 会「掉」进下一个 case 继续往下执行。比如 case 1 漏了 break，
 *     选了 1 之后 case 2、case 3 的代码也会被执行一遍。
 *
 *  2) 靠循环体里的 break 或 return。第 6 课：
 *     break 跳出循环，return 直接结束整个程序。
 *     本题选 0 时用的是 return 0。
 *
 *  3) 返回 0 表示「一个数都没读到」，也就是用户敲的不是数字（比如 abc）；
 *     返回 EOF 表示「输入已经结束了」，比如按了 Ctrl+D 或者管道里的数据用完了。
 *
 *  ▶ 小结（能用自己的话说出来就算真的会了）
 *  ---------------------------------------------------------------------------
 *  · 「菜单 → 分发 → 回到菜单」是所有交互式程序的骨架：
 *    while 管循环，switch 管分发，break 管退出。
 *  · switch 里的 break 一个都不能漏，漏了不会报错，
 *    只会安静地算错结果 —— 所以要养成「每个 case 结尾都写 break」的习惯。
 *  · 功能一样的 case 可以合并成一个 case 组，代码只写一遍，
 *    以后改起来也只改一处。
 *  · 读用户输入一定要看 scanf 的返回值，
 *    并且读失败后要把输入行里没读走的字符清掉，不然会一直卡住。
 * ============================================================================ */
