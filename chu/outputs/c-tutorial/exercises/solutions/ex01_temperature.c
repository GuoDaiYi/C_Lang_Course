/*
 * ============================================================================
 *  练习 1 参考答案：温度换算器
 * ============================================================================
 *
 *  ▶ 这个练习要练什么
 *  ---------------------------------------------------------------------------
 *    把一个温度换成另外两种温度。练的是「读数 → 套公式 → 打印」这条
 *    最基本的流水线，对应第 2 课（变量与数据类型）和第 3 课（输入输出）。
 *
 *    这道题的重点不在数学，在「怎么把公式变成代码」：
 *    公式里的常数要不要起名字？整数除法会不会坑你？打完怎么核对？
 *
 *  ▶ 前置知识（开始前先自测）
 *  ---------------------------------------------------------------------------
 *    ✅ 已经会：第 2 课：变量与数据类型（int / double、赋值、算术运算、const）
 *    ✅ 已经会：第 3 课：让程序会问问题（printf 提问、scanf 读数、看返回值）
 *    🔁 忘了就看：第 2 课第 3 节「算术运算与自增」、第 2 课第 5 节「const」
 *    🔁 忘了就看：第 3 课第 1 节「读一个整数」、第 3 课第 3 节「用 scanf 的返回值做输入校验」
 *    ❓ 自测（答案在文件末尾）
 *       1) 读一个 double 到变量 x，scanf 的格式符该写 %d 还是 %lf？
 *       2) int x = 7 / 2;  之后 x 是几？
 *       3) 为什么这里要写 9.0 / 5.0，而不是 9 / 5？
 *
 *  ▶ 题目要求（做完练习再看）
 *  ---------------------------------------------------------------------------
 *    程序先问「请输入摄氏温度（例如 36.5）：」，你敲一个数回车，
 *    它就把这个温度同时换算成华氏度和开尔文，用一行打印出来：
 *
 *      华氏度 = 摄氏度 * ratio + fahrenheit_offset
 *      开尔文 = 摄氏度 + kelvin_offset
 *
 *    验收样例（这是真的跑出来的输出，可以直接和你的程序对照）：
 *      输入 100  然后回车
 *      请输入摄氏温度（例如 36.5）：
 *      100.00 摄氏度 = 212.00 华氏度 = 373.15 开尔文
 *
 *      输入 -40  然后回车
 *      请输入摄氏温度（例如 36.5）：
 *      -40.00 摄氏度 = -40.00 华氏度 = 233.15 开尔文
 *
 *  ▶ 需要用到的语法（速查）
 *  ---------------------------------------------------------------------------
 *    1) double 变量
 *       写法：double celsius = 0.0;
 *       作用：装小数。C 里小数默认用 double，不要用 float。
 *       坑：赋值用单个等号 =，不是双等号 ==。== 是「比较」，= 是「赋值」。
 *
 *    2) const 常量
 *       写法：const double ratio = 9.0 / 5.0;
 *       作用：这个值定下来就不改了，给它起个名字比到处写 9.0 / 5.0 好懂得多。
 *       坑：const 变量只能初始化一次，赋第二次值编译器会报错。
 *
 *    3) printf 的 %.2f
 *       写法：printf("%.2f", x);
 *       作用：把 x 按「小数点后 2 位」打印出来，例如 36.5 → 36.50。
 *       坑：%f 会按默认的 6 位小数打印（36.500000），不好看。
 *
 *    4) 算术运算与运算顺序
 *       写法：celsius * ratio + fahrenheit_offset
 *       作用：* 乘、/ 除、+ 加，全部从左往右算，乘除优先于加减。
 *       坑：整数除法会丢小数。9 / 5 在整数里等于 1，
 *            所以比例要写成 9.0 / 5.0 才是 1.8。
 *
 *    5) scanf("%lf", &x)
 *       写法：scanf("%lf", &celsius)
 *       作用：把键盘上敲的数读进 celsius。
 *       坑：double 必须用 %lf（字母 l 加 f）；漏掉 & 程序会直接崩掉；
 *            & 的意思是「celsius 这个盒子的地址」。
 *
 *  ▶ 解法思路（先看思路，再看代码）
 *  ---------------------------------------------------------------------------
 *    1) 先想清楚「输入是什么、输出是什么、公式是什么」。
 *       输入：一个 double（摄氏温度）。
 *       输出：三个 double（摄氏、华氏、开尔文），一次 printf 打印。
 *       公式：华氏度 = 摄氏度 * 9 / 5 + 32，开尔文 = 摄氏度 + 273.15。
 *
 *    2) 再把公式里的常数取名字，这是这道题最有价值的一步。
 *       9 / 5 每次都要解释一遍太啰嗦，而且 9 / 5 会做整数除法变成 1，
 *       所以写成 const double ratio = 9.0 / 5.0；
 *       32 和 273.15 同理，分别叫 fahrenheit_offset 和 kelvin_offset。
 *       好处：以后改比例只改一个地方，代码读起来也像一句人话。
 *
 *    3) 然后按「声明 → 提问 → 读入并校验 → 计算 → 打印」的顺序写。
 *       读入那一步别忘了检查 scanf 的返回值：它返回成功读到的个数，
 *       不等于 1 就说明用户敲的不是数字，这时候该提示并结束。
 *
 *    4) 最后核对：输入 100 应该得到 212.00 和 373.15；
 *       输入 -40 应该得到 -40.00（摄氏和华氏唯一的交点）。
 *       两组都对上了，这道题就真的会了。
 *
 *    提醒：这题最容易被写错的地方是比例。
 *          写成 9 / 5 得到的是 1，程序不会报错，只会安静地算出一堆错数，
 *          所以一定要用已知答案（100 → 212）去核对。
 *
 *  ▶ 代码怎么读
 *  ---------------------------------------------------------------------------
 *    下面每段代码前面都有「▶▶▶ 第 N 段」，讲清这段在干嘛、跑起来会看到什么。
 *    建议顺序：先扫一眼每段的小标题 → 读代码 → 在脑子里预演输出 →
 *      最后把文件关掉，凭记忆重新写一遍，这样才真的学会。
 *
 *    第 1 段：准备三个变量。
 *    第 2 段：把公式里的常数取名字（ratio / fahrenheit_offset / kelvin_offset）。
 *    第 3 段：问用户要一个温度。
 *    第 4 段：把输入读进来，并检查读成功没有。
 *    第 5 段：套公式算出华氏度和开尔文 —— 这就是练习里 TODO 1 的答案。
 *    第 6 段：一次把三个温度打印出来。
 *    第 7 段（加分项）：打印一张常用温度对照表。
 *
 *  运行方式（在本项目根目录下）：
 *    make run L=exercises/solutions/ex01_temperature
 *    参考答案：exercises/solutions/ex01_temperature.c（先自己做再看）
 * ============================================================================
 */

#include <stdio.h>

int main(void) {
    /* ▶▶▶ 第 1 段：准备三个变量
     *  做什么：先把「摄氏 / 华氏 / 开尔文」三个盒子准备好，都先装 0.0。
     *  为什么先给 0.0：声明的时候顺手给个初值是好习惯，
     *                   编译器就不会警告「这个变量还没用过」。
     *  预期输出：屏幕上什么都还没有。
     */
    double celsius = 0.0;
    double fahrenheit = 0.0;
    double kelvin = 0.0;

    /* ▶▶▶ 第 2 段：把公式里的「魔法数字」取个名字
     *  做什么：公式里反复出现的常数，给它起个名字，以后一眼就知道是什么：
     *
     *    ratio             = 9.0 / 5.0 = 1.8  摄氏度每差 1 度，华氏度差 1.8 度
     *    fahrenheit_offset = 32.0             摄氏度 0 度时，对应华氏度 32 度
     *    kelvin_offset     = 273.15           摄氏度 0 度时，对应开尔文 273.15
     *
     *  ★ 这里故意写 9.0 / 5.0，不写 9 / 5：
     *    9 / 5 两边都是整数，C 会做「整数除法」，小数部分直接被丢掉，结果是 1。
     *    9.0 / 5.0 里有小数，才是真正的 1.8。
     *    对照着记：
     *      错误：const double ratio = 9 / 5;      → ratio 是 1.0，后面全错
     *      正确：const double ratio = 9.0 / 5.0;  → ratio 是 1.8，没问题
     *
     *  新语法：const —— 「这个值定下来就不改了」（第 2 课）。
     */
    const double ratio = 9.0 / 5.0;
    const double fahrenheit_offset = 32.0;
    const double kelvin_offset = 273.15;

    /* ▶▶▶ 第 3 段：问用户要一个温度
     *  做什么：printf 打印一句话。末尾故意不加 \n，
     *          这样用户敲的数会紧跟在冒号后面，看起来像接在同一行。
     *  预期输出：请输入摄氏温度（例如 36.5）：
     */
    printf("请输入摄氏温度（例如 36.5）：");

    /* ▶▶▶ 第 4 段：把用户输入的数读进来，并检查有没有读成功
     *  做什么：scanf("%lf", &celsius) 读一个小数。
     *          它会返回「成功读到了几个数」：读到 1 个是成功；
     *          读到 0 个说明用户敲的不是数字（比如 abc）；
     *          EOF 说明输入已经结束了（按了 Ctrl+D）。
     *  预期输出（输入 abc 时）：输入的不是数字，程序结束。
     */
    if (scanf("%lf", &celsius) != 1) {
        printf("输入的不是数字，程序结束。\n");
        return 1;
    }

    /* ▶▶▶ 第 5 段：套公式，算出华氏度和开尔文
     *  做什么：这就是练习里 TODO 1 的答案。
     *            华氏度 = 摄氏度 * ratio + fahrenheit_offset
     *            开尔文 = 摄氏度 + kelvin_offset
     *  预期输出（输入 100 时）：这行还不打印，只是把两个数算好放着。
     */
    fahrenheit = celsius * ratio + fahrenheit_offset;
    kelvin = celsius + kelvin_offset;

    /* ▶▶▶ 第 6 段：把三个温度一次打印出来
     *  做什么：开头的 \n 让结果另起一行；%.2f 表示每个数保留 2 位小数。
     *  预期输出（输入 100 时）：
     *            100.00 摄氏度 = 212.00 华氏度 = 373.15 开尔文
     */
    printf("\n%.2f 摄氏度 = %.2f 华氏度 = %.2f 开尔文\n",
           celsius, fahrenheit, kelvin);

    /* ▶▶▶ 第 7 段（加分项）：打印一张常用温度对照表
     *  做什么：把 0、20、37、100 四组温度排成一张对齐的小表格。
     *  用到的东西：数组、for 循环（第 6、8 课），
     *              sizeof(samples) / sizeof(samples[0]) 是「数组有几个元素」
     *              （第 8 课第 4 节），这样以后改数组内容，count 不用跟着改。
     *  预期输出：
     *            --- 常用温度对照表 ---
     *             摄氏度    华氏度    开尔文
     *                   0.0        32.00       273.15
     *                  20.0        68.00       293.15
     *                  37.0        98.60       310.15
     *                 100.0       212.00       373.15
     */
    printf("\n--- 常用温度对照表 ---\n");
    printf("%10s %12s %12s\n", "摄氏度", "华氏度", "开尔文");

    double samples[] = {0, 20, 37, 100};
    int count = sizeof(samples) / sizeof(samples[0]);

    for (int i = 0; i < count; i++) {
        double c = samples[i];
        printf("%10.1f %12.2f %12.2f\n", c, c * ratio + fahrenheit_offset, c + kelvin_offset);
    }

    return 0;
}

/* ============================================================================
 *  ▶ 常见报错速查
 *  ---------------------------------------------------------------------------
 *  error: expected ';' before '}' token
 *      → 上一行忘了写分号。看报错行号的上一行。
 *
 *  warning: implicit declaration of function 'scanf'
 *      → 忘了写 #include <stdio.h>。
 *
 *  warning: format '%lf' expects argument of type 'double *', but argument 2 has type 'double'
 *      → 读 double 忘了写 &。scanf 要的是地址，不是值。
 *
 *  运行时直接崩掉（段错误 / Segmentation fault）
 *      → 十有八九是 scanf 漏了 &，或者变量名拼错了。
 *
 *  算出来的华氏度永远是 180.00 这种怪数
 *      → 比例用错了。9 / 5 是整数除法等于 1，要写 9.0 / 5.0。
 *
 *  ▶ 自测答案
 *  ---------------------------------------------------------------------------
 *  1) %lf（字母 l 加 f）。%d 是给 int 用的；float 用 %f，double 用 %lf。
 *
 *  2) 3。7 / 2 两边都是整数，C 做整数除法，小数部分被丢掉了，
 *     所以结果是 3 不是 3.5。
 *
 *  3) 因为 9 / 5 是整数除法，结果直接变成 1；写成 9.0 / 5.0 才是 1.8。
 *     比例写错，后面所有结果都会离谱。
 *
 *  ▶ 小结（能用自己的话说出来就算真的会了）
 *  ---------------------------------------------------------------------------
 *  · 一个小程序的标准骨架就是：声明变量 → 问用户要输入 → 算 → 打印。
 *  · 公式里的常数取个名字（比如 ratio），代码会好懂得多，
 *    而且改比例的时候只需要改一个地方。
 *  · 整数除法是新手最常见的坑：9 / 5 等于 1，不是 1.8。
 *  · 想知道算对了没有，就把已知答案（100 摄氏度 = 212 华氏度）敲进去对一遍。
 * ============================================================================ */
