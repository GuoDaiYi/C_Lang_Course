#include <stdio.h>

/* ▶▶▶ 第 1 段：四个函数的声明（原型）
 *  做什么：告诉编译器「下面这四个函数存在，叫什么名字、
 *          收什么参数、返回什么」。这样 main 里就可以直接调用它们，
 *          哪怕它们的定义写在文件后面。
 *  提示：声明和后面的定义必须一模一样，一个字都不能差。
 */
int sum_of(const int scores[], int count);
int max_of(const int scores[], int count);
int min_of(const int scores[], int count);
double average_of(const int scores[], int count);

int main(void) {
    /* ▶▶▶ 第 2 段：准备数组和「有几个数」
     *  做什么：scores 是一排 5 个装成绩的格子；
     *          count 用 sizeof 自动算出来，以后把 5 改成 10 也不用改这里。
     *  预期输出：屏幕上什么都还没有。
     */
    int scores[5] = {0};
    const int count = sizeof(scores) / sizeof(scores[0]);

    /* ▶▶▶ 第 3 段：循环读入 5 个成绩
     *  做什么：一个一个问、一个一个读。
     *          scanf 返回值不等于 1，说明用户敲的不是数字，
     *          那就提示一下并结束程序（不能带着脏数据往下算）。
     *  预期输出：
     *            请依次输入 5 个成绩：
     *            请输入第 1 个成绩：请输入第 2 个成绩：……
     */
    printf("请依次输入 %d 个成绩：\n", count);
    for (int i = 0; i < count; i++) {
        printf("请输入第 %d 个成绩：", i + 1);
        if (scanf("%d", &scores[i]) != 1) {
            printf("输入的不是整数，程序结束。\n");
            return 1;
        }
    }

    /* ▶▶▶ 第 4 段：调用四个函数，把统计结果打印出来
     *  做什么：先算出四个结果存进变量，再一条条打印。
     *          注意 average_of 前面那个 (double) 转换：
     *          没有它就是整数除法，82.2 会变成 82。
     *  预期输出：
     *            --- 统计结果 ---
     *            总分   : 411
     *            平均分 : 82.20
     *            最高分 : 100
     *            最低分 : 55
     */
    int total = sum_of(scores, count);
    double average = average_of(scores, count);
    int best = max_of(scores, count);
    int worst = min_of(scores, count);

    printf("\n--- 统计结果 ---\n");
    printf("总分   : %d\n", total);
    printf("平均分 : %.2f\n", average);
    printf("最高分 : %d\n", best);
    printf("最低分 : %d\n", worst);

    /* ▶▶▶ 第 5 段：数及格 / 不及格的人数
     *  做什么：循环一遍数组，数一数有多少个 >= 60；
     *          不及格的人数 = 总人数 - 及格人数，不用再循环一次。
     *  预期输出：
     *            及格   : 4 人，不及格: 1 人
     */
    /* 统计及格人数 */
    int pass = 0;
    for (int i = 0; i < count; i++) {
        if (scores[i] >= 60) {
            pass++;
        }
    }
    printf("及格   : %d 人，不及格: %d 人\n", pass, count - pass);

    /* ▶▶▶ 第 6 段：列出高于平均分的成绩
     *  做什么：把每个成绩和平均分比一比，比平均分大的就打印出来。
     *          顺便用 above 数一下打印了几个，
     *          一个都没有的时候补一句「（没有）」，免得留一行空白看不懂。
     *  预期输出：
     *            高于平均分的有：88 92 100
     */
    /* 高于平均分的成绩 */
    printf("高于平均分的有：");
    int above = 0;
    for (int i = 0; i < count; i++) {
        if (scores[i] > average) {
            printf("%d ", scores[i]);
            above++;
        }
    }
    if (above == 0) {
        printf("（没有）");
    }
    printf("\n");

    return 0;
}

/* ▶▶▶ 第 7 段：sum_of —— 求所有成绩的总和
 *  做什么：total 先归 0，然后循环里把每个成绩加进去。
 *  关键点：用 +=（加上再存回去），不是 = （覆盖）。
 */
int sum_of(const int scores[], int count) {
    int total = 0;
    for (int i = 0; i < count; i++) {
        total += scores[i];
    }
    return total;
}

/* ▶▶▶ 第 8 段：max_of —— 求最高分
 *  做什么：先把第 0 个成绩当「目前最高」，然后和后面每一个比，
 *          比它大就换人。
 *  关键点：初始值用 scores[0]，不要用 0。
 *          因为成绩有可能全是负数，初始值 0 的话结果会错。
 */
int max_of(const int scores[], int count) {
    int best = scores[0];
    for (int i = 1; i < count; i++) {
        if (scores[i] > best) {
            best = scores[i];
        }
    }
    return best;
}

/* ▶▶▶ 第 9 段：min_of —— 求最低分
 *  做什么：和 max_of 一个套路，只不过改成比小。
 */
int min_of(const int scores[], int count) {
    int worst = scores[0];
    for (int i = 1; i < count; i++) {
        if (scores[i] < worst) {
            worst = scores[i];
        }
    }
    return worst;
}

/* ▶▶▶ 第 10 段：average_of —— 求平均分
 *  做什么：先用 sum_of 求总和，再除以个数。
 *  关键点：(double) 这个转换必须有。
 *          没有它就是「整数 ÷ 整数」，小数部分被丢掉。
 */
double average_of(const int scores[], int count) {
    if (count <= 0) {
        return 0.0;
    }
    return (double)sum_of(scores, count) / count;
}

/* ============================================================================
 *  ▶ 常见报错速查
 *  ---------------------------------------------------------------------------
 *  error: implicit declaration of function 'sum_of'
 *      → 忘了写函数声明（TODO 1）。或者声明和定义的写法不一样。
 *
 *  error: invalid types 'int' and 'double' for binary operator '+'
 *      → 把 int 和 double 混着加了。要么都用 int，要么把其中一个转成 double。
 *
 *  数组越界（有时候不报错，只是结果莫名其妙）
 *      → 下标写错了。5 个元素的数组，下标只有 0~4。
 *      → 循环写成 i <= count 也会多读一格，要写 i < count。
 *
 *  平均分总是少一点点（比如 82 而不是 82.2）
 *      → 整数除法！sum_of 返回的是 int，要先转成 double 再除：
 *         (double)sum_of(scores, count) / count
 *
 *  scanf("%d", scores[i]) 之后数据全是乱的
 *      → 漏了 &。scanf 要的是地址：scanf("%d", &scores[i])
 *
 *  ▶ 自测答案
 *  ---------------------------------------------------------------------------
 *  1) 4。下标从 0 开始，5 个元素的下标是 0、1、2、3、4。
 *
 *  2) += 是「加上再存回去」。total = data[i] 是「覆盖」，
 *     每次循环都会把前面累加的结果冲掉，最后只会剩下最后一个数。
 *
 *  3) 收到数组本身（写 const int scores[]），
 *     再额外收到一个 count 告诉它有几个元素 —— 因为数组作参数时，
 *     函数只知道开头在哪，不知道有多长。
 *
 *  ▶ 小结（能用自己的话说出来就算真的会了）
 *  ---------------------------------------------------------------------------
 *  · 「一批数据 + 几个统计结果」是 C 里最常见的套路：
 *    数组存数据，for 遍历，函数负责一种统计。
 *  · 求平均分最容易翻车的地方是整数除法：
 *    先转成 double 再除，不然小数部分会被丢掉。
 *  · 数组下标从 0 开始，最大下标 = 长度 - 1；循环条件写 i < count。
 *  · 把「求和 / 求最大 / 求最小」拆成三个小函数，
 *    好处是 main 读起来像人话，而且每个函数都短、好检查。
 * ============================================================================ */
