/*
 * ============================================================================
 *  练习 2 参考答案：乘法表
 * ============================================================================
 *
 *  ▶ 这个练习要练什么
 *  ---------------------------------------------------------------------------
 *    把一张 n × n 的乘法表打印出来。练的是「嵌套循环」：
 *    外层循环管行，内层循环管列。对应第 6 课（循环）和第 7 课（函数）。
 *
 *    这道题真正要弄懂的是两件事：
 *    一是「外层管行、内层管列」这个分工；
 *    二是「%-4d」为什么能让表格对齐。
 *
 *  ▶ 前置知识（开始前先自测）
 *  ---------------------------------------------------------------------------
 *    ✅ 已经会：第 6 课：循环（for 循环、嵌套循环）
 *    ✅ 已经会：第 7 课：函数（把打印逻辑抽成 print_table，main 只管输入）
 *    ✅ 已经会：第 2 课：变量与数据类型（int、printf 的格式符）
 *    🔁 忘了就看：第 6 课第 1 节「for 循环」、第 6 课第 6 节「嵌套循环」
 *    🔁 忘了就看：第 7 课第 1 节「最简单的调用」、第 7 课第 4 节「值传递」
 *    ❓ 自测（答案在文件末尾）
 *       1) for (int row = 1; row <= n; row++) 这句一共会执行几次循环体？
 *       2) 两层 for 套在一起，如果 n = 3，最内层的 printf 一共会执行几次？
 *       3) printf("%-4d", 7) 和 printf("%d", 7) 打出来有什么不一样？
 *
 *  ▶ 题目要求（做完练习再看）
 *  ---------------------------------------------------------------------------
 *    程序先问「请输入一个 1-12 之间的整数：」，你敲一个数回车，
 *    它就打印出这张 n × n 的乘法表，每一格的格式是「被乘数*乘数=结果」。
 *
 *    验收样例（这是真的跑出来的输出，可以直接和你的程序对照）：
 *      输入 3  然后回车
 *      请输入一个 1-12 之间的整数：
 *      --- 3 x 3 乘法表 ---
 *      1*1=1   2*1=2   3*1=3
 *      1*2=2   2*2=4   3*2=6
 *      1*3=3   2*3=6   3*3=9
 *
 *      注意：每格末尾有 3 个看不见的空格，那是因为 %-4d 要占 4 个字符宽。
 *
 *  ▶ 需要用到的语法（速查）
 *  ---------------------------------------------------------------------------
 *    1) for 循环
 *       写法：for (int row = 1; row <= n; row++) { ... }
 *       作用：从 1 数到 n，每次加 1，把循环体执行 n 遍。
 *       坑：循环变量写在 for 里面，只能在循环体里用（第 6 课）。
 *
 *    2) 嵌套循环
 *       写法：外层 for 里面再套一个 for
 *       作用：外层管「第几行」，内层管「这一行的第几格」。
 *             执行次数是 n × n（n=3 就是 9 次）。
 *       坑：内层的循环变量必须每次重新从 1 开始，别把 col = 1 写到外面。
 *
 *    3) printf 的 %-4d
 *       写法：printf("%d*%d=%-4d", col, row, row * col);
 *       作用：%-4d = 左对齐 + 至少占 4 个字符宽。数字右边补空格，
 *             这样每一格宽度一样，表格才对得齐。
 *       坑：写成 %d（不带宽度）的话，「1」占 1 格、「12」占 2 格，
 *             表格就会歪掉。
 *
 *    4) 算术表达式当参数
 *       写法：row * col
 *       作用：printf 的参数可以是算式，函数会先把算式的值算出来再打印。
 *       坑：* 是乘号，不是指针，这里别想复杂了。
 *
 *  ▶ 解法思路（先看思路，再看代码）
 *  ---------------------------------------------------------------------------
 *    1) 先想清楚「要打印多少格、每格打什么」。
 *       一共 n 行，每行 n 格；每格是「列号*行号=乘积」。
 *
 *    2) 然后翻译成两层循环：
 *       外层 for 管行（row 从 1 到 n，一行一行地打印）；
 *       内层 for 管列（col 从 1 到 n，一格一格地打印）。
 *       行末再补一个 printf("\n")，不然所有格子会挤成一行。
 *
 *    3) 再处理「对齐」这件事。
 *       只写 %d 的话，「1」占 1 个字符、「12」占 2 个字符，列就歪了。
 *       改成 %-4d，规定每格固定占 4 个字符宽（数字不够就在右边补空格），
 *       表格立刻整齐。这是对齐的唯一秘诀。
 *
 *    4) 最后把打印逻辑装进函数 print_table(int n)，
 *       main 只负责「问用户要 n、检查 n 合不合法、调用函数」。
 *       这叫「把干活的代码和跟用户打交道的代码分开」，
 *       是写函数的最大好处（第 7 课）。
 *
 *    提醒：这题最容易被写错的地方有两个。
 *          一是把行号列号放反了（写成 row*col 会得到 1*1=1、1*2=2 这种排法）；
 *          二是忘了 %-4d 的宽度，表格歪了却不知道为什么。
 *
 *  ▶ 代码怎么读
 *  ---------------------------------------------------------------------------
 *    下面每段代码前面都有「▶▶▶ 第 N 段」，讲清这段在干嘛、跑起来会看到什么。
 *    建议顺序：先扫一眼每段的小标题 → 读代码 → 在脑子里预演输出 →
 *      最后把文件关掉，凭记忆重新写一遍，这样才真的学会。
 *
 *    第 1 段：print_table 的外层循环 —— 决定这是第几行。
 *    第 2 段：内层循环 —— 决定这一行的第几格。
 *    第 3 段：打印一格（就是练习里 TODO 1 的答案）。
 *    第 4 段：一行打完换行。
 *    第 5 段：main 读入 n，并检查 1~12 的范围。
 *    第 6 段：打印表头，再调用 print_table。
 *    第 7 段（加分项）：只打印三角形那半张表。
 *
 *  运行方式（在本项目根目录下）：
 *    make run L=exercises/solutions/ex02_multiplication
 *    参考答案：exercises/solutions/ex02_multiplication.c
 * ============================================================================
 */

#include <stdio.h>

/* 把打印逻辑抽成函数，main 只负责输入和校验 —— 这是好习惯 */
void print_table(int n) {
    /* ▶▶▶ 第 1 段：外层循环 —— 决定这是第几行
     *  做什么：row 从 1 数到 n，每数一个就多打印一整行。
     *  预期输出：循环一共走 n 遍（第 1 行、第 2 行 ……）。
     */
    for (int row = 1; row <= n; row++) {
        /* ▶▶▶ 第 2 段：内层循环 —— 决定这一行的第几格
         *  做什么：col 从 1 数到 n，每次打印一格。
         *  预期输出：一行里会打印 n 格；两段循环合起来一共 n × n 格。
         */
        for (int col = 1; col <= n; col++) {
            /* ▶▶▶ 第 3 段：打印一格（这就是练习里 TODO 1 的答案）
             *  写法拆开看：
             *    "%d*%d=%-4d"  是模板：列号 * 行号 = 乘积（乘积占 4 格、左对齐）
             *    col          是被乘数（这一格是第几列）
             *    row          是乘数（这是第几行）
             *    row * col    是乘积
             *  预期输出（n = 3 时，第 1 行）：
             *    1*1=1   2*1=2   3*1=3
             */
            printf("%d*%d=%-4d", col, row, row * col);
        }
        /* ▶▶▶ 第 4 段：一行打完要换行
         *  做什么：内层循环结束说明这一行的 n 格都打完了，
         *          换行，好让下一行从行首开始。
         */
        printf("\n");       /* 一行打完换行 */
    }
}

/* 加分项：只打印三角形那半张表 */
void print_triangle_table(int n) {
    /* ▶▶▶ 第 5 段（加分项）：另一个函数 print_triangle_table —— 内层条件换成 col <= row
     *  做什么：和外层唯一的区别是内层循环的结束条件。
     *          普通乘法表是 col <= n（每行都打满 n 格），
     *          三角形只打 col <= row（第 1 行 1 格，第 2 行 2 格……）。
     *  预期输出（n = 3 时）：
     *    1*1=1
     *    1*2=2   2*2=4
     *    1*3=3   2*3=6   3*3=9
     */
    for (int row = 1; row <= n; row++) {
        for (int col = 1; col <= row; col++) {
            printf("%d*%d=%-4d", col, row, row * col);
        }
        printf("\n");
    }
}

int main(void) {
    int n = 0;

    /* ▶▶▶ 第 6 段：问用户要一个 n，并检查 1~12 的范围
     *  做什么：先问，再读；读到不是整数就报错退出；
     *          读到整数还要检查范围，超范围也退出。
     *  预期输出（输入 3）：
     *            请输入一个 1-12 之间的整数：
     */
    printf("请输入一个 1-12 之间的整数：");

    if (scanf("%d", &n) != 1) {
        printf("输入的不是整数。\n");
        return 1;
    }

    if (n < 1 || n > 12) {
        printf("只能输入 1 到 12 之间的数字。\n");
        return 1;
    }

    /* ▶▶▶ 第 7 段：打印表头，再调用 print_table
     *  做什么：先打印一行标题，然后交给 print_table 去画表。
     *  预期输出（输入 3）：
     *            --- 3 x 3 乘法表 ---
     *            1*1=1   2*1=2   3*1=3
     *            1*2=2   2*2=4   3*2=6
     *            1*3=3   2*3=6   3*3=9
     */
    printf("\n--- %d x %d 乘法表 ---\n", n, n);
    print_table(n);

    /* ▶▶▶ 第 8 段（加分项）：再打一张三角形的半张表
     *  预期输出（输入 3）：
     *            --- 三角形版本 ---
     *            1*1=1
     *            1*2=2   2*2=4
     *            1*3=3   2*3=6   3*3=9
     */
    printf("\n--- 三角形版本 ---\n");
    print_triangle_table(n);

    return 0;
}

/* ============================================================================
 *  ▶ 常见报错速查
 *  ---------------------------------------------------------------------------
 *  error: expected ';' before '}' token
 *      → 上一行忘了写分号。看报错行号的上一行。
 *
 *  warning: implicit declaration of function 'printf'
 *      → 忘了写 #include <stdio.h>。
 *
 *  warning: format '%d' expects argument of type 'int', but argument has type 'double'
 *      → 格式符和变量类型对不上。int 用 %d，double 用 %f / %lf。
 *
 *  表格歪了 / 每列没对齐
 *      → 宽度格式符写错了。要用 %-4d 这种带宽度和左对齐的写法，
 *        不能只写 %d。
 *
 *  只打印了一行
 *      → 内层循环写成了 col = 1（只判断一次）或 col <= 1。
 *        内层循环每次都要重新从 1 开始。
 *
 *  ▶ 自测答案
 *  ---------------------------------------------------------------------------
 *  1) n 次（row 从 1 到 n，每数一个执行一遍循环体）。
 *
 *  2) 9 次。外层 3 遍，每一遍里内层跑 3 遍，3 × 3 = 9。
 *
 *  3) %d 只打「7」，占 1 个字符宽；%-4d 打「7   」（数字加 3 个空格），
 *     左边对齐、总共占 4 个字符宽，这样表格才对得齐。
 *
 *  ▶ 小结（能用自己的话说出来就算真的会了）
 *  ---------------------------------------------------------------------------
 *  · 外层循环管行、内层循环管列，两层套起来就是一张表。
 *  · printf 的宽度格式符（%-4d）是让表格对齐的关键：
 *    不写宽度，每格宽度就不一样，表格必然歪。
 *  · 把「打印表格」这种活儿装进一个函数，main 就只剩下「跟用户打交道」，
 *    代码读起来清楚多了 —— 这就是函数的意义。
 * ============================================================================ */
