/* 读一个整数：
 *   读到的数放在全局变量 last_int 里
 *   返回  0 -> 读成功
 *   返回 -1 -> 输入的不是数字
 *   返回 -2 -> 输入已经结束（Ctrl+D 或输入重定向用完了） */
int read_int(void) {
    int rc = scanf("%d", &last_int);

    if (rc == EOF) {
        printf("\n");
        return -2;
    }
    clear_rest_of_line();
    if (rc != 1) {
        return -1;
    }
    printf("\n");     /* 读完了，换一行，免得下面的提示挤在一起 */
    return 0;
}

/* 读一个小数，用法和 read_int 一样，只是格式符是 %lf */
int read_number(void) {
    int rc = scanf("%lf", &last_number);

    if (rc == EOF) {
        printf("\n");
        return -2;
    }
    clear_rest_of_line();
    if (rc != 1) {
        return -1;
    }
    printf("\n");
    return 0;
}

/* 把输入缓冲区里剩下的字符（包括换行）全部读掉 */
void clear_rest_of_line(void) {
    int c;
    while ((c = getchar()) != '\n' && c != EOF) {
    }
}

