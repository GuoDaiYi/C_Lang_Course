#include <stdio.h>

int main(void) {
    /* ▶▶▶ 第 1 段：准备三个变量
     *  做什么：先把「摄氏 / 华氏 / 开尔文」三个盒子准备好，都先装 0.0。
     *  为什么先给 0.0：声明的时候顺手给个初值是好习惯，
     *                   编译器就不会警告「这个变量还没用过」。
     *  预期输出：屏幕上什么都还没有。
     */
    double celsius = 0.0;
    double fahrenheit = 0.0;
    double kelvin = 0.0;

    /* ▶▶▶ 第 2 段：先认识一下公式里的三个「常数」
     *  做什么：这一步先不写代码，只认识一下公式里会出现的三个数：
     *
     *    ratio             = 9.0 / 5.0 = 1.8  摄氏度每差 1 度，华氏度差 1.8 度
     *    fahrenheit_offset = 32.0             摄氏度 0 度时，对应华氏度 32 度
     *    kelvin_offset     = 273.15           摄氏度 0 度时，对应开尔文 273.15
     *
     *  ★ 为什么是 9.0 / 5.0，不写 9 / 5：
     *    9 / 5 两边都是整数，C 会做「整数除法」，小数部分直接被丢掉，结果是 1。
     *    9.0 / 5.0 里有小数，才是真正的 1.8。
     *    对照着记：
     *      错误：double ratio = 9 / 5;      → ratio 是 1.0，后面全错
     *      正确：double ratio = 9.0 / 5.0;  → ratio 是 1.8，没问题
     *
     *  这三个数写成变量（名字就用上面这三个）有两个好处：
     *    一是读代码时一眼知道是什么，不用猜；
     *    二是以后要改比例，只改一个地方就够了。
     *  具体怎么写，第 5 段（TODO 1）的提示里已经写好了。
     */

    /* ▶▶▶ 第 3 段：问用户要一个温度
     *  做什么：printf 打印一句话。末尾故意不加 \n，
     *          这样用户敲的数会紧跟在冒号后面，看起来像接在同一行。
     *  预期输出：请输入摄氏温度（例如 36.5）：
     */
    printf("请输入摄氏温度（例如 36.5）：");

    /* ▶▶▶ 第 4 段：把用户输入的数读进来，并检查有没有读成功
     *  做什么：scanf("%lf", &celsius) 读一个小数。
     *          它会返回「成功读到了几个数」：读到 1 个是成功；
     *          读到 0 个说明用户敲的不是数字（比如 abc）；
     *          EOF 说明输入已经结束了（按了 Ctrl+D）。
     *  预期输出（输入 abc 时）：输入的不是数字，程序结束。
     */
    if (scanf("%lf", &celsius) != 1) {   /* double 要用 %lf，别忘了 & */
        printf("输入的不是数字，程序结束。\n");
        return 1;
    }

    /* ▶▶▶ 第 5 段：★ 你要动手的地方 —— 把两个公式填进去
     *  做什么：分两小步。
     *
     *  第一步：在下面两行的上面，补上三个常量（公式里的常数取个名字）：
     *    const double ratio = 9.0 / 5.0;
     *    const double fahrenheit_offset = 32.0;
     *    const double kelvin_offset = 273.15;
     *  （新语法：const —— 「这个值定下来就不改了」，第 2 课。
     *    名字不要改，改了就对不上下面两行的算式。）
     *
     *  第二步：把下面两行的 0.0 换成真正的算式：
     *    华氏度 = 摄氏度 * ratio + fahrenheit_offset
     *    开尔文 = 摄氏度 + kelvin_offset
     *
     *  改完的样子：
     *    fahrenheit = celsius * ratio + fahrenheit_offset;
     *    kelvin     = celsius + kelvin_offset;
     *
     *  预期输出（输入 100 时）：
     *    100.00 摄氏度 = 212.00 华氏度 = 373.15 开尔文
     */
    /* TODO 1 ★ 把下面两行的 0.0 换成正确的算式（别忘了上面说的三个常量） */
    fahrenheit = 0.0;      /* 应改成：celsius * ratio + fahrenheit_offset */
    kelvin = 0.0;          /* 应改成：celsius + kelvin_offset */

    /* ▶▶▶ 第 6 段：把三个温度一次打印出来
     *  做什么：开头的 \n 让结果另起一行；%.2f 表示每个数保留 2 位小数。
     *  这一步已经写好了，公式一对，输出就正确了
     */
    printf("\n%.2f 摄氏度 = %.2f 华氏度 = %.2f 开尔文\n",
           celsius, fahrenheit, kelvin);

    /* ------------------------------------------------------------
     * 加分项（做完 TODO 1 再挑战）
     *
     * TODO 2: 打印一张对照表，把 0、20、37、100 度都算出来排成几行，
     *         表头写「摄氏度 / 华氏度 / 开尔文」。
     *         提示：可以用 for 循环配合数组，
     *               printf("%10.1f %12.2f %12.2f\n", c, f, k);
     *         小心：这里算出来的 f 和 k 也要用 ratio / fahrenheit_offset /
     *               kelvin_offset，别又写回 9 / 5。
     *
     * TODO 3: 输入不是数字时（比如输入 abc），提示得更友好一些，
     *         并让用户重新输入一次（提示：do-while + scanf 返回值）。
     * ------------------------------------------------------------ */

    return 0;
}

