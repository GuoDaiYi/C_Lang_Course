/* ============================================================================
 *  ▶ 常见报错速查
 *  ---------------------------------------------------------------------------
 *  error: expected ';' before '}' token
 *      → 上一行忘了写分号。看报错行号的上一行。
 *
 *  warning: implicit declaration of function 'scanf'
 *      → 忘了写 #include <stdio.h>。
 *
 *  warning: format '%lf' expects argument of type 'double *', but argument 2 has type 'double'
 *      → 读 double 忘了写 &。scanf 要的是地址，不是值。
 *
 *  运行时直接崩掉（段错误 / Segmentation fault）
 *      → 十有八九是 scanf 漏了 &，或者变量名拼错了。
 *
 *  算出来的华氏度永远是 180.00 这种怪数
 *      → 比例用错了。9 / 5 是整数除法等于 1，要写 9.0 / 5.0。
 *
 *  ▶ 自测答案
 *  ---------------------------------------------------------------------------
 *  1) %lf（字母 l 加 f）。%d 是给 int 用的；float 用 %f，double 用 %lf。
 *
 *  2) 3。7 / 2 两边都是整数，C 做整数除法，小数部分被丢掉了，
 *     所以结果是 3 不是 3.5。
 *
 *  3) 因为 9 / 5 是整数除法，结果直接变成 1；写成 9.0 / 5.0 才是 1.8。
 *     比例写错，后面所有结果都会离谱。
 *
 *  ▶ 小结（能用自己的话说出来就算真的会了）
 *  ---------------------------------------------------------------------------
 *  · 一个小程序的标准骨架就是：声明变量 → 问用户要输入 → 算 → 打印。
 *  · 公式写进代码之前，先问自己「运算顺序对不对」，特别是整数除法会丢小数。
 *  · 公式里的常数取个名字（比如 ratio），代码会好懂得多，
 *    而且改比例的时候只需要改一个地方。
 *  · 想知道算对了没有，就把已知答案（100 摄氏度 = 212 华氏度）敲进去对一遍。
 * ============================================================================ */
