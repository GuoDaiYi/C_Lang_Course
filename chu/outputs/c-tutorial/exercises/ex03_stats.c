int sum_of(const int scores[], int count) {
    int total = 0;
    for (int i = 0; i < count; i++) {
        total += scores[i];
    }
    return total;
}

int max_of(const int scores[], int count) {
    int best = scores[0];
    for (int i = 1; i < count; i++) {
        if (scores[i] > best) {
            best = scores[i];
        }
    }
    return best;
}

int min_of(const int scores[], int count) {
    int worst = scores[0];
    for (int i = 1; i < count; i++) {
        if (scores[i] < worst) {
            worst = scores[i];
        }
    }
    return worst;
}

double average_of(const int scores[], int count) {
    /* 防御性检查：一个数都没有的时候，直接返回 0，
     * 不要真的去除以 0（那是「除零」，行为不可预期）。 */
    if (count <= 0) {
        return 0.0;
    }
    return (double)sum_of(scores, count) / count;
}

